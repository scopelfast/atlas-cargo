-- Filha do lote e trilha de saldo. Idempotente.
-- Viagem sem TIPO_SALDO nao usa estas colunas.

ALTER TABLE "VIAGEMMESTRE" ADD COLUMN IF NOT EXISTS "IDVIAGEM_MAE" NUMERIC(15, 0) NULL;
ALTER TABLE "VIAGEMMESTRE" ADD COLUMN IF NOT EXISTS "ORIGEM_DERIVACAO" VARCHAR(30) NULL;
ALTER TABLE "VIAGEMMESTRE" ADD COLUMN IF NOT EXISTS "VALOR_CONSUMIDO_EMBARQUES" INTEGER NULL;
ALTER TABLE "VIAGEMMESTRE" ADD COLUMN IF NOT EXISTS "VALOR_CONSUMIDO_TON" NUMERIC(15, 3) NULL;

CREATE TABLE IF NOT EXISTS "VIAGEM_DERIVACAO_AUDITORIA" (
  "ID" BIGSERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL,
  "IDVIAGEM_MAE" NUMERIC(15, 0) NOT NULL,
  "IDVIAGEM_FILHA" NUMERIC(15, 0) NULL,
  "IDCONVOCACAO" INTEGER NULL,
  "EVENTO" VARCHAR(20) NOT NULL,
  "SALDO_ANTES" NUMERIC(15, 3) NULL,
  "SALDO_DEPOIS" NUMERIC(15, 3) NULL,
  "QTD_EMBARQUES" INTEGER NULL,
  "QTD_TON" NUMERIC(15, 3) NULL,
  "USUARIO" VARCHAR(50) NULL,
  "DH_EVENTO" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "DETALHES" VARCHAR(500) NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_VIAGEM_DERIV_AUD_CONV_EVENTO"
  ON "VIAGEM_DERIVACAO_AUDITORIA" ("TENANT_ID", "IDCONVOCACAO", "EVENTO")
  WHERE "IDCONVOCACAO" IS NOT NULL;
