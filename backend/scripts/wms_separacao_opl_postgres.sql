-- WMS — importação espelho OPL / separação (pedidos tipo 2 + itens tipo 3).
-- PostgreSQL, idempotente. Executar após wms_cadastros_mestre_postgres.sql (FK opcional CD_DONO).

CREATE TABLE IF NOT EXISTS "WMS_OPL_ARQUIVO" (
  "CD_OPL_ARQUIVO" SERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_DONO" INTEGER REFERENCES "WMS_DONO_ESTOQUE" ("CD_DONO") ON DELETE SET NULL,
  "NM_ARQUIVO" VARCHAR(255) NOT NULL,
  "HASH_CONTEUDO" CHAR(64) NOT NULL,
  "LINHA1_RAW" TEXT,
  "IDENT_TIPO1" CHAR(1),
  "CNPJ_CPF_CLI" VARCHAR(20),
  "CLI_NOME" VARCHAR(200),
  "DATA_ARQ" VARCHAR(12),
  "DH_IMPORT" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64),
  "Q_PEDIDOS" INTEGER NOT NULL DEFAULT 0,
  "Q_ITENS" INTEGER NOT NULL DEFAULT 0,
  "ST_IMPORT" VARCHAR(20) NOT NULL DEFAULT 'IMPORTADO'
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_wms_opl_arquivo_tenant_hash
  ON "WMS_OPL_ARQUIVO" ("TENANT_ID", "HASH_CONTEUDO");

CREATE INDEX IF NOT EXISTS idx_wms_opl_arquivo_tenant_dh
  ON "WMS_OPL_ARQUIVO" ("TENANT_ID", "DH_IMPORT" DESC);

CREATE TABLE IF NOT EXISTS "WMS_OPL_PEDIDO" (
  "CD_OPL_PEDIDO" SERIAL PRIMARY KEY,
  "CD_OPL_ARQUIVO" INTEGER NOT NULL REFERENCES "WMS_OPL_ARQUIVO" ("CD_OPL_ARQUIVO") ON DELETE CASCADE,
  "SEQ_PEDIDO" INTEGER NOT NULL,
  "LINHA2_RAW" TEXT,
  "COD_DESTINATARIO" VARCHAR(20),
  "RAZ_SOC_DEST" VARCHAR(200),
  "ENDE_ENTREGA" VARCHAR(200),
  "BAIRRO_ENTREGA" VARCHAR(80),
  "CEP_ENTREGA" VARCHAR(20),
  "CIDADE_ENTREGA" VARCHAR(80),
  "UF_ENTREGA" CHAR(2),
  "NUM_PEDIDO" VARCHAR(20),
  "DATA_PEDIDO" VARCHAR(12),
  "CNPJ_DEST" VARCHAR(20),
  "FONE_DEST" VARCHAR(80),
  "DADOS_JSON" JSONB,
  CONSTRAINT uq_wms_opl_pedido_arquivo_seq UNIQUE ("CD_OPL_ARQUIVO", "SEQ_PEDIDO")
);

CREATE INDEX IF NOT EXISTS idx_wms_opl_pedido_arquivo ON "WMS_OPL_PEDIDO" ("CD_OPL_ARQUIVO");

CREATE TABLE IF NOT EXISTS "WMS_OPL_ITEM" (
  "CD_OPL_ITEM" SERIAL PRIMARY KEY,
  "CD_OPL_PEDIDO" INTEGER NOT NULL REFERENCES "WMS_OPL_PEDIDO" ("CD_OPL_PEDIDO") ON DELETE CASCADE,
  "SEQ_ITEM" INTEGER NOT NULL,
  "LINHA3_RAW" TEXT,
  "DESCRICAO" VARCHAR(200),
  "COD_PRODUTO_OL" VARCHAR(40),
  "QT_PEDIDA" NUMERIC(18, 6) NOT NULL DEFAULT 0,
  "QT_COLETADA" NUMERIC(18, 6),
  "REF_PEDIDO_LINK" VARCHAR(20),
  "DADOS_JSON" JSONB,
  CONSTRAINT uq_wms_opl_item_pedido_seq UNIQUE ("CD_OPL_PEDIDO", "SEQ_ITEM")
);

CREATE INDEX IF NOT EXISTS idx_wms_opl_item_pedido ON "WMS_OPL_ITEM" ("CD_OPL_PEDIDO");
