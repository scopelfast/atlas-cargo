-- Script para adicionar Gerenciar Tipos de Atividade ao menu
-- Execute este script no banco de dados

-- 1. Inserir/Atualizar na tabela TIPOATIVIDADE
-- Nota: Este módulo gerencia a própria tabela TIPOATIVIDADE
-- Você pode usar um código que ainda não existe, por exemplo: 99

MERGE INTO TIPOATIVIDADE AS TARGET
USING (VALUES (99, '9.2.Gerenciar Tipos de Atividade', 'S', GETDATE(), 'SYSTEM', 'AppDVcargas', 'gerenciar-tipos-atividade'))
AS SOURCE (CDTIPOATIVIDADE, DSTIPOATIVIDADE, FGACTIVE, DHMAINTENANCE, SGUSER, SERVERORIG, DSPROGRAMA)
ON (TARGET.CDTIPOATIVIDADE = SOURCE.CDTIPOATIVIDADE)
WHEN MATCHED THEN
    UPDATE SET
        DSTIPOATIVIDADE = SOURCE.DSTIPOATIVIDADE,
        FGACTIVE = SOURCE.FGACTIVE,
        DHMAINTENANCE = SOURCE.DHMAINTENANCE,
        SGUSER = SOURCE.SGUSER,
        SERVERORIG = SOURCE.SERVERORIG,
        DSPROGRAMA = SOURCE.DSPROGRAMA
WHEN NOT MATCHED BY TARGET THEN
    INSERT (CDTIPOATIVIDADE, DSTIPOATIVIDADE, FGACTIVE, DHMAINTENANCE, SGUSER, SERVERORIG, DSPROGRAMA)
    VALUES (SOURCE.CDTIPOATIVIDADE, SOURCE.DSTIPOATIVIDADE, SOURCE.FGACTIVE, SOURCE.DHMAINTENANCE, SOURCE.SGUSER, SOURCE.SERVERORIG, SOURCE.DSPROGRAMA);

PRINT '   ✓ TIPOATIVIDADE "Gerenciar Tipos de Atividade" adicionado/atualizado.';
GO

