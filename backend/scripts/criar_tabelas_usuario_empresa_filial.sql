-- ============================================================================
-- Script para criar tabelas de associação de usuários com empresas e filiais
-- ============================================================================

-- Tabela USUARIOEMPRESA: Associa usuários a empresas
IF NOT EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[USUARIOEMPRESA]') AND type in (N'U'))
BEGIN
    CREATE TABLE [dbo].[USUARIOEMPRESA] (
        [SGUSUARIO] VARCHAR(50) NOT NULL,
        [CDEMPRESA] SMALLINT NOT NULL,
        [FGACTIVE] CHAR(1) NULL DEFAULT 'S',
        [DHMAINTENANCE] DATETIME NULL DEFAULT GETDATE(),
        [SGUSER] VARCHAR(50) NULL DEFAULT 'SYSTEM',
        [SERVERORIG] VARCHAR(50) NULL DEFAULT 'AppDVcargas',
        CONSTRAINT [PK_USUARIOEMPRESA] PRIMARY KEY ([SGUSUARIO], [CDEMPRESA]),
        CONSTRAINT [FK_USUARIOEMPRESA_USUARIO] FOREIGN KEY ([SGUSUARIO]) 
            REFERENCES [dbo].[USUARIO]([SGUSUARIO]),
        CONSTRAINT [FK_USUARIOEMPRESA_EMPRESA] FOREIGN KEY ([CDEMPRESA]) 
            REFERENCES [dbo].[EMPRESA]([CDEMPRESA])
    );
    
    PRINT 'Tabela USUARIOEMPRESA criada com sucesso.';
END
ELSE
BEGIN
    PRINT 'Tabela USUARIOEMPRESA já existe.';
END
GO

-- Tabela USUARIOFILIAL: Associa usuários a filiais
IF NOT EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[USUARIOFILIAL]') AND type in (N'U'))
BEGIN
    CREATE TABLE [dbo].[USUARIOFILIAL] (
        [SGUSUARIO] VARCHAR(50) NOT NULL,
        [CDEMPRESA] SMALLINT NOT NULL,
        [CDFILIAL] SMALLINT NOT NULL,
        [FGACTIVE] CHAR(1) NULL DEFAULT 'S',
        [DHMAINTENANCE] DATETIME NULL DEFAULT GETDATE(),
        [SGUSER] VARCHAR(50) NULL DEFAULT 'SYSTEM',
        [SERVERORIG] VARCHAR(50) NULL DEFAULT 'AppDVcargas',
        CONSTRAINT [PK_USUARIOFILIAL] PRIMARY KEY ([SGUSUARIO], [CDEMPRESA], [CDFILIAL]),
        CONSTRAINT [FK_USUARIOFILIAL_USUARIO] FOREIGN KEY ([SGUSUARIO]) 
            REFERENCES [dbo].[USUARIO]([SGUSUARIO]),
        CONSTRAINT [FK_USUARIOFILIAL_FILIAL] FOREIGN KEY ([CDEMPRESA], [CDFILIAL]) 
            REFERENCES [dbo].[FILIAL]([CDEMPRESA], [CDFILIAL])
    );
    
    PRINT 'Tabela USUARIOFILIAL criada com sucesso.';
END
ELSE
BEGIN
    PRINT 'Tabela USUARIOFILIAL já existe.';
END
GO

-- Índices para melhorar performance
IF NOT EXISTS (SELECT * FROM sys.indexes WHERE name = 'IX_USUARIOEMPRESA_SGUSUARIO' AND object_id = OBJECT_ID('USUARIOEMPRESA'))
BEGIN
    CREATE INDEX [IX_USUARIOEMPRESA_SGUSUARIO] ON [dbo].[USUARIOEMPRESA]([SGUSUARIO]);
END
GO

IF NOT EXISTS (SELECT * FROM sys.indexes WHERE name = 'IX_USUARIOEMPRESA_CDEMPRESA' AND object_id = OBJECT_ID('USUARIOEMPRESA'))
BEGIN
    CREATE INDEX [IX_USUARIOEMPRESA_CDEMPRESA] ON [dbo].[USUARIOEMPRESA]([CDEMPRESA]);
END
GO

IF NOT EXISTS (SELECT * FROM sys.indexes WHERE name = 'IX_USUARIOFILIAL_SGUSUARIO' AND object_id = OBJECT_ID('USUARIOFILIAL'))
BEGIN
    CREATE INDEX [IX_USUARIOFILIAL_SGUSUARIO] ON [dbo].[USUARIOFILIAL]([SGUSUARIO]);
END
GO

IF NOT EXISTS (SELECT * FROM sys.indexes WHERE name = 'IX_USUARIOFILIAL_EMPRESA_FILIAL' AND object_id = OBJECT_ID('USUARIOFILIAL'))
BEGIN
    CREATE INDEX [IX_USUARIOFILIAL_EMPRESA_FILIAL] ON [dbo].[USUARIOFILIAL]([CDEMPRESA], [CDFILIAL]);
END
GO

PRINT 'Índices criados com sucesso.';
GO

