-- adicionar_tabela_liberacao_divergencia_expedicao_postgres.sql
-- Objetivo: registrar liberacoes de expedicao com divergencia de forma estruturada.
-- Executar no pgAdmin, banco atlas_cargo_prd (PostgreSQL).

CREATE TABLE IF NOT EXISTS "WMS_EXPEDICAO_LIBERACAO_DIVERGENCIA" (
  "CD_LIBERACAO" BIGSERIAL PRIMARY KEY,
  "CD_CARGA" INTEGER NOT NULL REFERENCES "WMS_CARGA_PROGRAMADA" ("CD_CARGA") ON DELETE CASCADE,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "DH_LIBERACAO" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64) NOT NULL,
  "AUTORIZADO_POR" VARCHAR(120) NOT NULL,
  "AUTORIZADO_LOGIN" VARCHAR(50),
  "AUTORIZADO_NOME" VARCHAR(120),
  "JUSTIFICATIVA" VARCHAR(1000) NOT NULL,
  "DIVERGENCIAS_JSON" JSONB
);

ALTER TABLE "WMS_EXPEDICAO_LIBERACAO_DIVERGENCIA"
  ADD COLUMN IF NOT EXISTS "AUTORIZADO_LOGIN" VARCHAR(50);

ALTER TABLE "WMS_EXPEDICAO_LIBERACAO_DIVERGENCIA"
  ADD COLUMN IF NOT EXISTS "AUTORIZADO_NOME" VARCHAR(120);

CREATE INDEX IF NOT EXISTS "idx_wms_liberacao_divergencia_tenant_carga"
  ON "WMS_EXPEDICAO_LIBERACAO_DIVERGENCIA" ("TENANT_ID", "CD_CARGA", "DH_LIBERACAO" DESC);
