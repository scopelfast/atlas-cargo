-- WMS — auditoria de liberação da política de validade mínima no recebimento (PostgreSQL).
-- Idempotente. Relacionado: docs/WMS_ESTRATEGIA_INVENTARIO_ALERTAS_DASHBOARDS.md

CREATE TABLE IF NOT EXISTS "WMS_RECEBIMENTO_LIBERACAO_VALIDADE" (
  "CD_LIBERACAO" BIGSERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_NFE" INTEGER NOT NULL,
  "CD_DONO" INTEGER NOT NULL,
  "TP_ACAO" VARCHAR(24) NOT NULL,
  "NU_DIAS_MIN_POLITICA" INTEGER,
  "FALHAS_JSON" JSONB,
  "JUSTIFICATIVA" VARCHAR(1000) NOT NULL,
  "SG_USER_OPERADOR" VARCHAR(64) NOT NULL,
  "AUTORIZADO_LOGIN" VARCHAR(50),
  "AUTORIZADO_NOME" VARCHAR(120),
  "DH_LIBERACAO" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_wms_rec_lib_val_tp CHECK ("TP_ACAO" IN ('CONFERENCIA', 'ENCERRAR'))
);

CREATE INDEX IF NOT EXISTS "idx_wms_rec_lib_val_tenant_nfe"
  ON "WMS_RECEBIMENTO_LIBERACAO_VALIDADE" ("TENANT_ID", "CD_NFE", "DH_LIBERACAO" DESC);

CREATE INDEX IF NOT EXISTS "idx_wms_rec_lib_val_tenant_dono"
  ON "WMS_RECEBIMENTO_LIBERACAO_VALIDADE" ("TENANT_ID", "CD_DONO", "DH_LIBERACAO" DESC);

COMMENT ON TABLE "WMS_RECEBIMENTO_LIBERACAO_VALIDADE" IS 'Supervisor autorizou salvar conferência ou encerrar NF com validade abaixo do mínimo do dono.';
