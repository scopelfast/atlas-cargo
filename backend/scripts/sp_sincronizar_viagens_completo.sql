-- ============================================
-- Stored Procedure: sp_sincronizar_viagens_completo
-- ============================================
-- Esta procedure encapsula toda a lógica de sincronização
-- para melhorar a performance e evitar timeouts
-- ============================================

USE [ATLAS_CARGO_PRD];
GO

-- Remover procedure se já existir
IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[sp_sincronizar_viagens_completo]') AND type in (N'P', N'PC'))
    DROP PROCEDURE [dbo].[sp_sincronizar_viagens_completo];
GO

CREATE PROCEDURE [dbo].[sp_sincronizar_viagens_completo]
AS
BEGIN
    SET NOCOUNT ON;
    
    BEGIN TRY
        BEGIN TRANSACTION;
        
        -- ============================================
        -- Criar tabelas se não existirem
        -- ============================================
        
        -- Tabela: VIAGEMMOTORISTA
        IF NOT EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[VIAGEMMOTORISTA]') AND type in (N'U'))
        BEGIN
            CREATE TABLE [dbo].[VIAGEMMOTORISTA] (
                [IDVIAGEM] DECIMAL(15, 0) NOT NULL,
                [CDMOTORISTA] DECIMAL(15, 0) NOT NULL,
                [DHMAINTENANCE] DATETIME NULL,
                [SGUSER] VARCHAR(50) NULL,
                [SERVERORIG] VARCHAR(50) NULL,
                CONSTRAINT [PK_VIAGEMMOTORISTA] PRIMARY KEY CLUSTERED ([IDVIAGEM] ASC, [CDMOTORISTA] ASC)
            );
        END
        
        -- Adicionar constraints se não existirem
        IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[VIAGEMMESTRE]') AND type in (N'U'))
        BEGIN
            IF NOT EXISTS (SELECT * FROM sys.foreign_keys WHERE name = 'FK_VIAGEMMOTORISTA_VIAGEMMESTRE')
            BEGIN
                ALTER TABLE [dbo].[VIAGEMMOTORISTA]
                ADD CONSTRAINT [FK_VIAGEMMOTORISTA_VIAGEMMESTRE] FOREIGN KEY ([IDVIAGEM]) 
                    REFERENCES [dbo].[VIAGEMMESTRE] ([IDVIAGEM]) ON DELETE CASCADE;
            END
        END
        
        IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[CADASTROGERAL]') AND type in (N'U'))
        BEGIN
            IF NOT EXISTS (SELECT * FROM sys.foreign_keys WHERE name = 'FK_VIAGEMMOTORISTA_CADASTROGERAL')
            BEGIN
                ALTER TABLE [dbo].[VIAGEMMOTORISTA]
                ADD CONSTRAINT [FK_VIAGEMMOTORISTA_CADASTROGERAL] FOREIGN KEY ([CDMOTORISTA]) 
                    REFERENCES [dbo].[CADASTROGERAL] ([CDCADASTRO]) ON DELETE CASCADE;
            END
        END
        
        -- Tabela: VIAGEMVEICULO
        IF NOT EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[VIAGEMVEICULO]') AND type in (N'U'))
        BEGIN
            CREATE TABLE [dbo].[VIAGEMVEICULO] (
                [IDVIAGEM] DECIMAL(15, 0) NOT NULL,
                [IDEQUIPAMENTO] DECIMAL(15, 0) NOT NULL,
                [REFEQUIPAMENTO] VARCHAR(20) NOT NULL,
                [TPEQUIPAMENTO] CHAR(2) NOT NULL,
                [DHMAINTENANCE] DATETIME NULL,
                [SGUSER] VARCHAR(50) NULL,
                [SERVERORIG] VARCHAR(50) NULL,
                CONSTRAINT [PK_VIAGEMVEICULO] PRIMARY KEY CLUSTERED ([IDVIAGEM] ASC, [IDEQUIPAMENTO] ASC)
            );
        END
        
        -- Adicionar constraints se não existirem
        IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[VIAGEMMESTRE]') AND type in (N'U'))
        BEGIN
            IF NOT EXISTS (SELECT * FROM sys.foreign_keys WHERE name = 'FK_VIAGEMVEICULO_VIAGEMMESTRE')
            BEGIN
                ALTER TABLE [dbo].[VIAGEMVEICULO]
                ADD CONSTRAINT [FK_VIAGEMVEICULO_VIAGEMMESTRE] FOREIGN KEY ([IDVIAGEM]) 
                    REFERENCES [dbo].[VIAGEMMESTRE] ([IDVIAGEM]) ON DELETE CASCADE;
            END
        END
        
        IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[EQUIPAMENTO]') AND type in (N'U'))
        BEGIN
            IF NOT EXISTS (SELECT * FROM sys.foreign_keys WHERE name = 'FK_VIAGEMVEICULO_EQUIPAMENTO')
            BEGIN
                ALTER TABLE [dbo].[VIAGEMVEICULO]
                ADD CONSTRAINT [FK_VIAGEMVEICULO_EQUIPAMENTO] FOREIGN KEY ([IDEQUIPAMENTO]) 
                    REFERENCES [dbo].[EQUIPAMENTO] ([IDEQUIPAMENTO]) ON DELETE CASCADE;
            END
        END
        
        -- ============================================
        -- Sincronizar VIAGEMMESTRE
        -- ============================================
        UPDATE d
        SET 
            CDTIPOVIAGEM       = SOURCE.CDTIPOVIAGEM,
            CDSITUACAOVIAGEM   = SOURCE.CDSITUACAOVIAGEM,
            FGSITVIAGEM        = SOURCE.FGSITVIAGEM,
            CDCLASSEFROTA      = SOURCE.CDCLASSEFROTA,
            CDCONTRATADOR      = SOURCE.CDCONTRATADOR,
            IDROTEIRO          = SOURCE.IDROTEIRO,
            DISTANCIAKM        = SOURCE.DISTANCIAKM,
            DHINCLUSAO         = SOURCE.DHINCLUSAO,
            SGUSERINCLUSAO     = SOURCE.SGUSERINCLUSAO,
            DTPREVINICIO       = SOURCE.DTPREVINICIO,
            DTPREVFINAL        = SOURCE.DTPREVFINAL,
            OBSERV             = SOURCE.OBSERV,
            VLFRETE            = SOURCE.VLFRETE,
            PESO               = SOURCE.PESO,
            CUBAGEM            = SOURCE.CUBAGEM,
            DHMAINTENANCE      = GETDATE(),
            SGUSER             = 'SYSTEM',
            SERVERORIG         = SOURCE.SERVERORIG
        FROM [dbo].[VIAGEMMESTRE] d
        INNER JOIN (
            SELECT DISTINCT 
                VM.IDVIAGEM,
                VM.CDTIPOVIAGEM,
                VM.CDSITUACAOVIAGEM,
                VM.FGSITVIAGEM,
                VM.CDCLASSEFROTA,
                VM.CDCONTRATADOR,
                VM.IDROTEIRO,
                VM.DISTANCIAKM,
                VM.DHINCLUSAO,
                UPPER(ISNULL(VM.SGUSERINCLUSAO, 'SYSTEM')) AS SGUSERINCLUSAO,
                CONVERT(DATETIME, DATEADD(HOUR, ISNULL(VM.HRINIJANINICIO, 0), VM.DTPREVINICIO)) AS DTPREVINICIO,
                CONVERT(DATETIME, DATEADD(HOUR, ISNULL(VM.HRINIJANFINAL, 0), VM.DTPREVFINAL)) AS DTPREVFINAL,
                CASE 
                    WHEN DETALHES_FRETE.DETALHES IS NOT NULL THEN
                        CASE 
                            WHEN LEN(LTRIM(RTRIM(ISNULL(VM.OBSERV, '')))) > 0 THEN
                                UPPER(VM.OBSERV) + CHAR(13) + CHAR(10) + DETALHES_FRETE.DETALHES
                            ELSE
                                DETALHES_FRETE.DETALHES
                        END
                    ELSE
                        UPPER(ISNULL(VM.OBSERV, ''))
                END AS OBSERV,
                ISNULL(VL_FRETE.VLFRETE, 0) AS VLFRETE,
                CAST(ISNULL(PESO_CUBAGEM.PESO, 0) AS DECIMAL(15, 3)) AS PESO,
                CAST(ISNULL(PESO_CUBAGEM.CUBAGEM, 0) AS DECIMAL(15, 3)) AS CUBAGEM,
                ISNULL(VM.DHMAINTENANCE, GETDATE()) AS DHMAINTENANCE,
                UPPER(ISNULL(VM.SGUSER, 'SYSTEM')) AS SGUSER,
                ISNULL(VM.SERVERORIG, 'AppDVcargas') AS SERVERORIG
            FROM [INTEGRA_PRD].[dbo].[VIAGEMMESTRE] VM
            OUTER APPLY (
                SELECT 
                    STUFF((
                        SELECT CHAR(13) + CHAR(10) + 
                               TIPOPARCELA.DSTIPOPARCELA + ' - R$ ' + 
                               CONVERT(VARCHAR(20), CAST(VC.VLNEGOCIADO AS DECIMAL(15, 2)), 2)
                        FROM [INTEGRA_PRD].[dbo].[VIAGEMCONTRATO] VC
                        INNER JOIN [INTEGRA_PRD].[dbo].[TIPOPARCELA] TIPOPARCELA 
                            ON VC.SGTIPOPARCELA = TIPOPARCELA.SGTIPOPARCELA
                        WHERE VC.IDVIAGEM = VM.IDVIAGEM
                          AND TIPOPARCELA.FGTIPOPARCELA IN ('F', 'O', 'A')
                        ORDER BY VC.IDVIAGEM
                        FOR XML PATH(''), TYPE
                    ).value('.', 'NVARCHAR(MAX)'), 1, 2, '') AS DETALHES
            ) DETALHES_FRETE
            OUTER APPLY (
                SELECT 
                    CAST(SUM(VC.VLNEGOCIADO) AS DECIMAL(15, 4)) AS VLFRETE
                FROM [INTEGRA_PRD].[dbo].[VIAGEMCONTRATO] VC
                INNER JOIN [INTEGRA_PRD].[dbo].[TIPOPARCELA] TIPOPARCELA 
                    ON VC.SGTIPOPARCELA = TIPOPARCELA.SGTIPOPARCELA
                WHERE VC.IDVIAGEM = VM.IDVIAGEM
                  AND TIPOPARCELA.FGTIPOPARCELA IN ('F', 'O', 'A')
            ) VL_FRETE
            OUTER APPLY (
                SELECT 
                    SUM(COALESCE(SS.PESOPRODUTO, 0) + COALESCE(DFM.PESOBRUTO, 0)) AS PESO,
                    SUM(COALESCE(SS.CUBAGEM, 0) + COALESCE(DFM.CUBAGEM, 0)) AS CUBAGEM
                FROM [INTEGRA_PRD].[dbo].[VIAGEMDOCUMENTO] VD
                LEFT JOIN [INTEGRA_PRD].[dbo].[SOLICITACAOSERVICO] SS 
                    ON VD.SIGLADOC = 'SSV' AND VD.IDDOCUMENTO = SS.IDSOLICITACAOSERVICO
                LEFT JOIN [INTEGRA_PRD].[dbo].[DOCFISCALREF] DFR 
                    ON VD.SIGLADOC <> 'SSV' AND VD.IDDOCUMENTO = DFR.IDDOCFISCAL
                LEFT JOIN [INTEGRA_PRD].[dbo].[DOCFISCALMESTRE] DFM 
                    ON DFR.IDDOCREFERENCIA = DFM.IDDOCFISCAL
                WHERE VD.IDVIAGEM = VM.IDVIAGEM
            ) PESO_CUBAGEM
            WHERE VM.IDVIAGEM IS NOT NULL
        ) AS SOURCE
        ON d.IDVIAGEM = SOURCE.IDVIAGEM
        WHERE 
            ISNULL(d.CDTIPOVIAGEM, 0) <> ISNULL(SOURCE.CDTIPOVIAGEM, 0)
            OR ISNULL(d.CDSITUACAOVIAGEM, 0) <> ISNULL(SOURCE.CDSITUACAOVIAGEM, 0)
            OR ISNULL(d.FGSITVIAGEM, '') <> ISNULL(SOURCE.FGSITVIAGEM, '')
            OR ISNULL(d.CDCLASSEFROTA, 0) <> ISNULL(SOURCE.CDCLASSEFROTA, 0)
            OR ISNULL(d.CDCONTRATADOR, 0) <> ISNULL(SOURCE.CDCONTRATADOR, 0)
            OR ISNULL(d.IDROTEIRO, 0) <> ISNULL(SOURCE.IDROTEIRO, 0)
            OR ISNULL(d.DISTANCIAKM, 0) <> ISNULL(SOURCE.DISTANCIAKM, 0)
            OR ISNULL(d.DHINCLUSAO, '1900-01-01') <> ISNULL(SOURCE.DHINCLUSAO, '1900-01-01')
            OR ISNULL(d.SGUSERINCLUSAO, '') <> ISNULL(SOURCE.SGUSERINCLUSAO, '')
            OR ISNULL(d.DTPREVINICIO, '1900-01-01') <> ISNULL(SOURCE.DTPREVINICIO, '1900-01-01')
            OR ISNULL(d.DTPREVFINAL, '1900-01-01') <> ISNULL(SOURCE.DTPREVFINAL, '1900-01-01')
            OR ISNULL(d.OBSERV, '') <> ISNULL(SOURCE.OBSERV, '')
            OR ISNULL(d.VLFRETE, 0) <> ISNULL(SOURCE.VLFRETE, 0)
            OR ISNULL(d.PESO, 0) <> ISNULL(SOURCE.PESO, 0)
            OR ISNULL(d.CUBAGEM, 0) <> ISNULL(SOURCE.CUBAGEM, 0)
            OR ISNULL(d.DHMAINTENANCE, '1900-01-01') < ISNULL(SOURCE.DHMAINTENANCE, '1900-01-01');
        
        -- ============================================
        -- Sincronizar Tabelas de Referência
        -- ============================================
        
        -- CLASSEFROTA
        MERGE INTO [dbo].[CLASSEFROTA] AS TARGET
        USING (
            SELECT DISTINCT
                CDCLASSEFROTA,
                DSCLASSEFROTA,
                2 AS NREIXOS,
                CAPACIDCARGA,
                ISNULL(DHMAINTENANCE, GETDATE()) AS DHMAINTENANCE,
                ISNULL(SGUSER, 'SYSTEM') AS SGUSER,
                ISNULL(SERVERORIG, 'AppDVcargas') AS SERVERORIG,
                'A' AS FGACTIVE
            FROM [INTEGRA_PRD].[dbo].[CLASSEFROTA]
            WHERE CDCLASSEFROTA IS NOT NULL
              AND DSCLASSEFROTA IS NOT NULL
        ) AS SOURCE
        ON TARGET.CDCLASSEFROTA = SOURCE.CDCLASSEFROTA
        WHEN NOT MATCHED BY TARGET THEN
            INSERT (CDCLASSEFROTA, DSCLASSEFROTA, NREIXOS, CAPACIDCARGA, DHMAINTENANCE, SGUSER, SERVERORIG, FGACTIVE)
            VALUES (SOURCE.CDCLASSEFROTA, SOURCE.DSCLASSEFROTA, SOURCE.NREIXOS, SOURCE.CAPACIDCARGA, SOURCE.DHMAINTENANCE, SOURCE.SGUSER, SOURCE.SERVERORIG, SOURCE.FGACTIVE);
        
        -- TIPOVIAGEM
        MERGE INTO [dbo].[TIPOVIAGEM] AS TARGET
        USING (
            SELECT DISTINCT
                CDTIPOVIAGEM,
                DSTIPOVIAGEM,
                'A' AS FGACTIVE,
                ISNULL(DHMAINTENANCE, GETDATE()) AS DHMAINTENANCE,
                ISNULL(SGUSER, 'SYSTEM') AS SGUSER,
                ISNULL(SERVERORIG, 'AppDVcargas') AS SERVERORIG
            FROM [INTEGRA_PRD].[dbo].[TIPOVIAGEM]
            WHERE CDTIPOVIAGEM IS NOT NULL
              AND DSTIPOVIAGEM IS NOT NULL
        ) AS SOURCE
        ON TARGET.CDTIPOVIAGEM = SOURCE.CDTIPOVIAGEM
        WHEN NOT MATCHED BY TARGET THEN
            INSERT (CDTIPOVIAGEM, DSTIPOVIAGEM, FGACTIVE, DHMAINTENANCE, SGUSER, SERVERORIG)
            VALUES (SOURCE.CDTIPOVIAGEM, SOURCE.DSTIPOVIAGEM, SOURCE.FGACTIVE, SOURCE.DHMAINTENANCE, SOURCE.SGUSER, SOURCE.SERVERORIG);
        
        -- SITUACAOVIAGEM
        MERGE INTO [dbo].[SITUACAOVIAGEM] AS TARGET
        USING (
            SELECT DISTINCT
                CDSITUACAOVIAGEM,
                DSSITUACAOVIAGEM,
                'A' AS FGACTIVE,
                ISNULL(DHMAINTENANCE, GETDATE()) AS DHMAINTENANCE,
                ISNULL(SGUSER, 'SYSTEM') AS SGUSER,
                ISNULL(SERVERORIG, 'AppDVcargas') AS SERVERORIG
            FROM [INTEGRA_PRD].[dbo].[SITUACAOVIAGEM]
            WHERE CDSITUACAOVIAGEM IS NOT NULL
              AND DSSITUACAOVIAGEM IS NOT NULL
        ) AS SOURCE
        ON TARGET.CDSITUACAOVIAGEM = SOURCE.CDSITUACAOVIAGEM
        WHEN NOT MATCHED BY TARGET THEN
            INSERT (CDSITUACAOVIAGEM, DSSITUACAOVIAGEM, FGACTIVE, DHMAINTENANCE, SGUSER, SERVERORIG)
            VALUES (SOURCE.CDSITUACAOVIAGEM, SOURCE.DSSITUACAOVIAGEM, SOURCE.FGACTIVE, SOURCE.DHMAINTENANCE, SOURCE.SGUSER, SOURCE.SERVERORIG);
        
        -- ROTEIRO
        MERGE INTO [dbo].[ROTEIRO] AS TARGET
        USING (
            SELECT DISTINCT
                IDROTEIRO,
                CDCIDADEDESTINO,
                CDCIDADEORIGEM,
                DSROTEIRO,
                DISTANCIAKM,
                'S' AS FGACTIVE,
                ISNULL(DHMAINTENANCE, GETDATE()) AS DHMAINTENANCE,
                ISNULL(SGUSER, 'SYSTEM') AS SGUSER,
                ISNULL(SERVERORIG, 'AppDVcargas') AS SERVERORIG
            FROM [INTEGRA_PRD].[dbo].[ROTEIRO]
            WHERE IDROTEIRO IN (
                SELECT DISTINCT IDROTEIRO 
                FROM [INTEGRA_PRD].[dbo].[VIAGEMMESTRE]
                WHERE CDSITUACAOVIAGEM IN (1)
                  AND DHINCLUSAO > DATEADD(DAY, -07, GETDATE())
            )
              AND IDROTEIRO IS NOT NULL
        ) AS SOURCE
        ON TARGET.IDROTEIRO = SOURCE.IDROTEIRO
        WHEN NOT MATCHED BY TARGET THEN
            INSERT (IDROTEIRO, CDCIDADEDESTINO, CDCIDADEORIGEM, DSROTEIRO, DISTANCIAKM, FGACTIVE, DHMAINTENANCE, SGUSER, SERVERORIG)
            VALUES (SOURCE.IDROTEIRO, SOURCE.CDCIDADEDESTINO, SOURCE.CDCIDADEORIGEM, SOURCE.DSROTEIRO, SOURCE.DISTANCIAKM, SOURCE.FGACTIVE, SOURCE.DHMAINTENANCE, SOURCE.SGUSER, SOURCE.SERVERORIG)
        WHEN MATCHED THEN
            UPDATE SET
                CDCIDADEDESTINO = SOURCE.CDCIDADEDESTINO,
                CDCIDADEORIGEM = SOURCE.CDCIDADEORIGEM,
                DSROTEIRO = SOURCE.DSROTEIRO,
                DISTANCIAKM = SOURCE.DISTANCIAKM,
                FGACTIVE = ISNULL(TARGET.FGACTIVE, 'S'),
                DHMAINTENANCE = SOURCE.DHMAINTENANCE,
                SGUSER = SOURCE.SGUSER,
                SERVERORIG = SOURCE.SERVERORIG;
        
        -- ROTEIROPONTOS
        MERGE INTO [dbo].[ROTEIROPONTOS] AS TARGET
        USING (
            SELECT 
                RP.IDROTEIRO,
                RP.SEQUENCIA,
                RP.ORDEM,
                RP.DSLOCAL,
                RP.DSPOSICAO,
                RP.LATITUDE,
                RP.LONGITUDE,
                RP.TPLOCAL,
                RP.KMENTREPONTOS,
                ISNULL(RP.DHMAINTENANCE, GETDATE()) AS DHMAINTENANCE,
                ISNULL(RP.SGUSER, 'SYSTEM') AS SGUSER,
                ISNULL(RP.SERVERORIG, 'AppDVcargas') AS SERVERORIG,
                RP.CDPAISPASSAGEM,
                RP.ESTADOPASSAGEM
            FROM [INTEGRA_PRD].[dbo].[ROTEIROPONTOS] RP
            INNER JOIN [dbo].[ROTEIRO] R ON RP.IDROTEIRO = R.IDROTEIRO
            WHERE RP.IDROTEIRO IS NOT NULL
              AND RP.SEQUENCIA IS NOT NULL
              AND RP.DSLOCAL IS NOT NULL
              AND RP.DSPOSICAO IS NOT NULL
        ) AS SOURCE
        ON TARGET.IDROTEIRO = SOURCE.IDROTEIRO 
           AND TARGET.SEQUENCIA = SOURCE.SEQUENCIA
        WHEN MATCHED THEN
            UPDATE SET
                ORDEM = SOURCE.ORDEM,
                DSLOCAL = SOURCE.DSLOCAL,
                DSPOSICAO = SOURCE.DSPOSICAO,
                LATITUDE = SOURCE.LATITUDE,
                LONGITUDE = SOURCE.LONGITUDE,
                TPLOCAL = SOURCE.TPLOCAL,
                KMENTREPONTOS = SOURCE.KMENTREPONTOS,
                DHMAINTENANCE = SOURCE.DHMAINTENANCE,
                SGUSER = SOURCE.SGUSER,
                SERVERORIG = SOURCE.SERVERORIG,
                CDPAISPASSAGEM = SOURCE.CDPAISPASSAGEM,
                ESTADOPASSAGEM = SOURCE.ESTADOPASSAGEM
        WHEN NOT MATCHED BY TARGET THEN
            INSERT (IDROTEIRO, SEQUENCIA, ORDEM, DSLOCAL, DSPOSICAO, LATITUDE, LONGITUDE, TPLOCAL, KMENTREPONTOS, DHMAINTENANCE, SGUSER, SERVERORIG, CDPAISPASSAGEM, ESTADOPASSAGEM)
            VALUES (SOURCE.IDROTEIRO, SOURCE.SEQUENCIA, SOURCE.ORDEM, SOURCE.DSLOCAL, SOURCE.DSPOSICAO, SOURCE.LATITUDE, SOURCE.LONGITUDE, SOURCE.TPLOCAL, SOURCE.KMENTREPONTOS, SOURCE.DHMAINTENANCE, SOURCE.SGUSER, SOURCE.SERVERORIG, SOURCE.CDPAISPASSAGEM, SOURCE.ESTADOPASSAGEM);
        
        -- CADASTROGERAL - CONTRATADOR (Tipo O)
        MERGE INTO [dbo].[CADASTROGERAL] AS TARGET
        USING (
            SELECT DISTINCT
                CDCADASTRO,
                CGCCPF,
                RZSOCIAL,
                NMFANTASIA,
                FGFISICAJURIDICA,
                CEP,
                CDCIDADE,
                ENDERECO,
                NRENDERECO,
                COMPLEND,
                BAIRRO,
                NRCELULAR,
                ENDEMAIL,
                LATITUDE,
                LONGITUDE,
                ISNULL(FGACTIVE, 'A') AS FGACTIVE,
                'O' AS FGTIPOCADASTRO,
                ISNULL(DHMAINTENANCE, GETDATE()) AS DHMAINTENANCE,
                ISNULL(SGUSER, 'SYSTEM') AS SGUSER,
                ISNULL(SERVERORIG, 'AppDVcargas') AS SERVERORIG,
                NULL AS CDTRANSPORTADOR,
                'N' AS FGRASTREADO
            FROM [INTEGRA_PRD].[dbo].[CADASTROGERAL]
            WHERE CDCADASTRO IN (
                SELECT DISTINCT CDCONTRATADOR 
                FROM [INTEGRA_PRD].[dbo].[VIAGEMMESTRE]
                WHERE CDSITUACAOVIAGEM IN (1)
                  AND DHINCLUSAO > DATEADD(DAY, -07, GETDATE())
                  AND CDCONTRATADOR IS NOT NULL
            )
              AND CDCADASTRO IS NOT NULL
              AND RZSOCIAL IS NOT NULL
        ) AS SOURCE
        ON TARGET.CDCADASTRO = SOURCE.CDCADASTRO
        WHEN NOT MATCHED BY TARGET THEN
            INSERT (CDCADASTRO, CGCCPF, RZSOCIAL, NMFANTASIA, FGFISICAJURIDICA, CEP, CDCIDADE, ENDERECO, NRENDERECO, COMPLEND, BAIRRO, NRCELULAR, ENDEMAIL, LATITUDE, LONGITUDE, FGACTIVE, FGTIPOCADASTRO, DHMAINTENANCE, SGUSER, SERVERORIG, CDTRANSPORTADOR, FGRASTREADO)
            VALUES (SOURCE.CDCADASTRO, SOURCE.CGCCPF, SOURCE.RZSOCIAL, SOURCE.NMFANTASIA, SOURCE.FGFISICAJURIDICA, SOURCE.CEP, SOURCE.CDCIDADE, SOURCE.ENDERECO, SOURCE.NRENDERECO, SOURCE.COMPLEND, SOURCE.BAIRRO, SOURCE.NRCELULAR, SOURCE.ENDEMAIL, SOURCE.LATITUDE, SOURCE.LONGITUDE, SOURCE.FGACTIVE, SOURCE.FGTIPOCADASTRO, SOURCE.DHMAINTENANCE, SOURCE.SGUSER, SOURCE.SERVERORIG, SOURCE.CDTRANSPORTADOR, SOURCE.FGRASTREADO);
        
        -- CADASTROGERAL - TRANSPORTADOR (Tipo T)
        -- Usa a procedure dedicada sp_integracao_transportador para melhor performance
        IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[sp_integracao_transportador]') AND type in (N'P', N'PC'))
        BEGIN
            EXEC [dbo].[sp_integracao_transportador];
        END
        ELSE
        BEGIN
            -- Fallback: lógica antiga se a procedure não existir
            MERGE INTO [dbo].[CADASTROGERAL] AS TARGET
            USING (
                SELECT DISTINCT 
                    C.CDCADASTRO,
                    C.CGCCPF,
                    C.RZSOCIAL,
                    C.NMFANTASIA,
                    C.FGFISICAJURIDICA,
                    C.CEP,
                    C.CDCIDADE,
                    C.ENDERECO,
                    C.NRENDERECO,
                    C.COMPLEND,
                    C.BAIRRO,
                    C.NRCELULAR,
                    C.ENDEMAIL,
                    C.LATITUDE,
                    C.LONGITUDE,
                    ISNULL(C.FGACTIVE, 'A') AS FGACTIVE,
                    'T' AS FGTIPOCADASTRO,
                    ISNULL(C.DHMAINTENANCE, GETDATE()) AS DHMAINTENANCE,
                    ISNULL(C.SGUSER, 'SYSTEM') AS SGUSER,
                    ISNULL(C.SERVERORIG, 'AppDVcargas') AS SERVERORIG,
                    NULL AS CDTRANSPORTADOR,
                    CASE 
                        WHEN ER.SGUSER = 'RASTER' THEN 'S'
                        ELSE 'N'
                    END AS FGRASTREADO
                FROM [INTEGRA_PRD].[dbo].[CADASTROGERAL] C
                LEFT JOIN (
                    SELECT DISTINCT M.CDTRANSPORTADOR AS CDCADASTRO, 'RASTER' AS SGUSER
                    FROM [INTEGRA_PRD].[dbo].[VIAGEMMESTRE] VM
                    INNER JOIN [INTEGRA_PRD].[dbo].[VIAGEMMOTORISTA] MV ON VM.IDVIAGEM = MV.IDVIAGEM
                    INNER JOIN [INTEGRA_PRD].[dbo].[MOTORISTA] M ON MV.CDMOTORISTA = M.CDMOTORISTA
                    INNER JOIN [INTEGRA_PRD].[dbo].[VIAGEMVEICULO] VV ON VM.IDVIAGEM = VV.IDVIAGEM
                    INNER JOIN (
                        SELECT DISTINCT IDEQUIPAMENTO
                        FROM [INTEGRA_PRD].[dbo].[EQUIPAMENTORASTREAMENTO]
                        WHERE SGUSER = 'RASTER'
                          AND CONVERT(DATE, DHEVENTO) > CONVERT(DATE, GETDATE() - 30)
                    ) ER ON VV.IDEQUIPAMENTO = ER.IDEQUIPAMENTO
                    WHERE M.CDTRANSPORTADOR IS NOT NULL
                ) ER ON C.CDCADASTRO = ER.CDCADASTRO
                WHERE C.CDCADASTRO IN (
                    SELECT DISTINCT M.CDTRANSPORTADOR 
                    FROM [INTEGRA_PRD].[dbo].[VIAGEMMESTRE] VM
                    INNER JOIN [INTEGRA_PRD].[dbo].[VIAGEMMOTORISTA] MV ON VM.IDVIAGEM = MV.IDVIAGEM
                    INNER JOIN [INTEGRA_PRD].[dbo].[MOTORISTA] M ON MV.CDMOTORISTA = M.CDMOTORISTA
                    WHERE VM.CDSITUACAOVIAGEM IN (1)
