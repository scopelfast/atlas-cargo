                ON VV.IDVIAGEM = VM.IDVIAGEM
            INNER JOIN [dbo].[EQUIPAMENTO] E
                ON VV.IDEQUIPAMENTO = E.IDEQUIPAMENTO
        ) AS SOURCE
        ON TARGET.IDVIAGEM = SOURCE.IDVIAGEM 
           AND TARGET.IDEQUIPAMENTO = SOURCE.IDEQUIPAMENTO
        WHEN MATCHED THEN
            UPDATE SET
                REFEQUIPAMENTO = SOURCE.REFEQUIPAMENTO,
                TPEQUIPAMENTO = SOURCE.TPEQUIPAMENTO,
                DHMAINTENANCE = SOURCE.DHMAINTENANCE,
                SGUSER = SOURCE.SGUSER,
                SERVERORIG = SOURCE.SERVERORIG
        WHEN NOT MATCHED BY TARGET THEN
            INSERT (IDVIAGEM, IDEQUIPAMENTO, REFEQUIPAMENTO, TPEQUIPAMENTO, DHMAINTENANCE, SGUSER, SERVERORIG)
            VALUES (SOURCE.IDVIAGEM, SOURCE.IDEQUIPAMENTO, SOURCE.REFEQUIPAMENTO, SOURCE.TPEQUIPAMENTO, SOURCE.DHMAINTENANCE, SOURCE.SGUSER, SOURCE.SERVERORIG);
        
        -- ============================================
        -- DESATIVAR VIAGENS COM MOTORISTA DEFINIDO (ÚLTIMO PASSO)
        -- ============================================
        UPDATE d
        SET 
            d.FGACTIVE = 'N',
            d.CDSITUACAOVIAGEM = 2,
            d.OBSERV = ISNULL(d.OBSERV, '') + ' | ' + 'Viagem desativada por ter motorista definido',
            d.DHMAINTENANCE = GETDATE(),
            d.SGUSER = 'SYSTEM'
        FROM [dbo].[VIAGEMMESTRE] d
        INNER JOIN [INTEGRA_PRD].[dbo].[VIAGEMMESTRE] i ON d.IDVIAGEM = i.IDVIAGEM
        INNER JOIN [INTEGRA_PRD].[dbo].[VIAGEMMOTORISTA] vm ON i.IDVIAGEM = vm.IDVIAGEM
        WHERE i.CDSITUACAOVIAGEM = 1
          AND d.FGACTIVE = 'S';
        
        COMMIT TRANSACTION;
        
        SELECT 
            'SUCCESS' AS Status,
            'Sincronização concluída com sucesso!' AS Mensagem;
            
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;
        
        SELECT 
            'ERROR' AS Status,
            ERROR_MESSAGE() AS Mensagem,
            ERROR_NUMBER() AS NumeroErro,
            ERROR_LINE() AS LinhaErro;
    END CATCH
END;
GO
