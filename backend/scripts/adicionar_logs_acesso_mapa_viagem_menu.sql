-- Script para adicionar/atualizar Logs de Acesso e Mapa de Viagem no menu
-- Execute este script no banco de dados

-- 1. Atualizar "4.6.Logs de Acesso" (CDTIPOATIVIDADE = 4)
-- Usar MERGE para garantir que o registro seja criado se não existir
MERGE INTO TIPOATIVIDADE AS TARGET
USING (VALUES (4, '4.6.Logs de Acesso', 'S', GETDATE(), 'SYSTEM', 'AppDVcargas', 'gerenciar-logs-acesso'))
AS SOURCE (CDTIPOATIVIDADE, DSTIPOATIVIDADE, FGACTIVE, DHMAINTENANCE, SGUSER, SERVERORIG, DSPROGRAMA)
ON (TARGET.CDTIPOATIVIDADE = SOURCE.CDTIPOATIVIDADE)
WHEN MATCHED THEN
    UPDATE SET
        DSTIPOATIVIDADE = SOURCE.DSTIPOATIVIDADE,
        DSPROGRAMA = SOURCE.DSPROGRAMA,
        FGACTIVE = SOURCE.FGACTIVE,
        DHMAINTENANCE = SOURCE.DHMAINTENANCE,
        SGUSER = SOURCE.SGUSER,
        SERVERORIG = SOURCE.SERVERORIG
WHEN NOT MATCHED BY TARGET THEN
    INSERT (CDTIPOATIVIDADE, DSTIPOATIVIDADE, FGACTIVE, DHMAINTENANCE, SGUSER, SERVERORIG, DSPROGRAMA)
    VALUES (SOURCE.CDTIPOATIVIDADE, SOURCE.DSTIPOATIVIDADE, SOURCE.FGACTIVE, SOURCE.DHMAINTENANCE, SOURCE.SGUSER, SOURCE.SERVERORIG, SOURCE.DSPROGRAMA);

PRINT '✅ TIPOATIVIDADE "4.6.Logs de Acesso" atualizado/criado com DSPROGRAMA = gerenciar-logs-acesso.';
GO

-- 2. Atualizar "4.5.Mapa de Viagem" (CDTIPOATIVIDADE = 30)
-- Usar MERGE para garantir que o registro seja criado se não existir
MERGE INTO TIPOATIVIDADE AS TARGET
USING (VALUES (30, '4.5.Mapa de Viagem', 'S', GETDATE(), 'SYSTEM', 'AppDVcargas', 'gerenciar-mapa-viagem'))
AS SOURCE (CDTIPOATIVIDADE, DSTIPOATIVIDADE, FGACTIVE, DHMAINTENANCE, SGUSER, SERVERORIG, DSPROGRAMA)
ON (TARGET.CDTIPOATIVIDADE = SOURCE.CDTIPOATIVIDADE)
WHEN MATCHED THEN
    UPDATE SET
        DSTIPOATIVIDADE = SOURCE.DSTIPOATIVIDADE,
        DSPROGRAMA = SOURCE.DSPROGRAMA,
        FGACTIVE = SOURCE.FGACTIVE,
        DHMAINTENANCE = SOURCE.DHMAINTENANCE,
        SGUSER = SOURCE.SGUSER,
        SERVERORIG = SOURCE.SERVERORIG
WHEN NOT MATCHED BY TARGET THEN
    INSERT (CDTIPOATIVIDADE, DSTIPOATIVIDADE, FGACTIVE, DHMAINTENANCE, SGUSER, SERVERORIG, DSPROGRAMA)
    VALUES (SOURCE.CDTIPOATIVIDADE, SOURCE.DSTIPOATIVIDADE, SOURCE.FGACTIVE, SOURCE.DHMAINTENANCE, SOURCE.SGUSER, SOURCE.SERVERORIG, SOURCE.DSPROGRAMA);

PRINT '✅ TIPOATIVIDADE "4.5.Mapa de Viagem" atualizado/criado com DSPROGRAMA = gerenciar-mapa-viagem.';
GO

-- 3. Verificar se os registros foram atualizados corretamente
SELECT 
    CDTIPOATIVIDADE,
    DSTIPOATIVIDADE,
    DSPROGRAMA,
    FGACTIVE,
    FGGRUPO
FROM TIPOATIVIDADE
WHERE CDTIPOATIVIDADE IN (4, 30)
ORDER BY CDTIPOATIVIDADE;

