-- Criar tabela HISTORICOREABERTURA se não existir
IF NOT EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[HISTORICOREABERTURA]') AND type in (N'U'))
BEGIN
    CREATE TABLE [dbo].[HISTORICOREABERTURA] (
        [IDHISTORICO] INT IDENTITY(1,1) NOT NULL,
        [IDCONVOCACAO] INT NOT NULL,
        [IDVIAGEM] DECIMAL(15,0) NOT NULL,
        [CDCADASTRO_MOTORISTA] DECIMAL(15,0) NOT NULL,
        [STATUS_ANTERIOR] VARCHAR(20) NOT NULL, -- CONFIRMADA ou ACEITA_DESCARTADA
        [CDMOTIVOREABERTURA] INT NOT NULL,
        [DHRABERTURA] DATETIME NOT NULL DEFAULT GETDATE(),
        [SGUSUARIO_OPERADOR] VARCHAR(50) NOT NULL,
        [OBSERVACAO] VARCHAR(500) NULL,
        [FGACTIVE] CHAR(1) NOT NULL DEFAULT 'A', -- A=Ativo, I=Inativo
        [DHINCLUSAO] DATETIME NOT NULL DEFAULT GETDATE(),
        [SGUSERINCLUSAO] VARCHAR(50) NOT NULL DEFAULT 'SYSTEM',
        [DHMAINTENANCE] DATETIME NULL,
        [SGUSER] VARCHAR(50) NULL,
        [SERVERORIG] VARCHAR(50) NULL,
        CONSTRAINT [PK_HISTORICOREABERTURA] PRIMARY KEY CLUSTERED ([IDHISTORICO] ASC)
    );
    
    -- Adicionar Foreign Keys
    IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[CONVOCACAO]') AND type in (N'U'))
    BEGIN
        ALTER TABLE [dbo].[HISTORICOREABERTURA]
        ADD CONSTRAINT [FK_HISTORICOREABERTURA_CONVOCACAO] FOREIGN KEY ([IDCONVOCACAO])
        REFERENCES [dbo].[CONVOCACAO] ([IDCONVOCACAO]);
    END;
    
    IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[VIAGEMMESTRE]') AND type in (N'U'))
    BEGIN
        ALTER TABLE [dbo].[HISTORICOREABERTURA]
        ADD CONSTRAINT [FK_HISTORICOREABERTURA_VIAGEM] FOREIGN KEY ([IDVIAGEM])
        REFERENCES [dbo].[VIAGEMMESTRE] ([IDVIAGEM]);
    END;
    
    IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[CADASTROGERAL]') AND type in (N'U'))
    BEGIN
        ALTER TABLE [dbo].[HISTORICOREABERTURA]
        ADD CONSTRAINT [FK_HISTORICOREABERTURA_MOTORISTA] FOREIGN KEY ([CDCADASTRO_MOTORISTA])
        REFERENCES [dbo].[CADASTROGERAL] ([CDCADASTRO]);
    END;
    
    IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[MOTIVOREABERTURA]') AND type in (N'U'))
    BEGIN
        ALTER TABLE [dbo].[HISTORICOREABERTURA]
        ADD CONSTRAINT [FK_HISTORICOREABERTURA_MOTIVO] FOREIGN KEY ([CDMOTIVOREABERTURA])
        REFERENCES [dbo].[MOTIVOREABERTURA] ([CDMOTIVO]);
    END;
    
    PRINT 'Tabela HISTORICOREABERTURA criada com sucesso!';
END
ELSE
BEGIN
    PRINT 'Tabela HISTORICOREABERTURA já existe.';
END;
GO

-- Criar índice para melhorar performance de consultas
IF NOT EXISTS (SELECT * FROM sys.indexes WHERE name = 'IX_HISTORICOREABERTURA_IDVIAGEM' AND object_id = OBJECT_ID(N'[dbo].[HISTORICOREABERTURA]'))
BEGIN
    CREATE NONCLUSTERED INDEX [IX_HISTORICOREABERTURA_IDVIAGEM] 
    ON [dbo].[HISTORICOREABERTURA] ([IDVIAGEM] ASC);
    PRINT 'Índice IX_HISTORICOREABERTURA_IDVIAGEM criado.';
END;

IF NOT EXISTS (SELECT * FROM sys.indexes WHERE name = 'IX_HISTORICOREABERTURA_IDCONVOCACAO' AND object_id = OBJECT_ID(N'[dbo].[HISTORICOREABERTURA]'))
BEGIN
    CREATE NONCLUSTERED INDEX [IX_HISTORICOREABERTURA_IDCONVOCACAO] 
    ON [dbo].[HISTORICOREABERTURA] ([IDCONVOCACAO] ASC);
    PRINT 'Índice IX_HISTORICOREABERTURA_IDCONVOCACAO criado.';
END;
GO

