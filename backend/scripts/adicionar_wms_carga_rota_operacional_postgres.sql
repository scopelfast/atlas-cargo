-- Rota operacional planejada para WMS Carga Programada (POSTGRES)
-- Objetivo: persistir paradas + resultado OSRM sem alterar tabelas existentes do WMS.
-- Idempotente: CREATE TABLE IF NOT EXISTS + índices.

CREATE TABLE IF NOT EXISTS "WMS_CARGA_ROTA_OPERACIONAL" (
  "CD_ROTA_OPER"     BIGSERIAL PRIMARY KEY,
  "TENANT_ID"        VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_CARGA"         INTEGER NOT NULL REFERENCES "WMS_CARGA_PROGRAMADA" ("CD_CARGA") ON DELETE CASCADE,
  "VERSAO"           INTEGER NOT NULL DEFAULT 1,
  "ST_ROTA"          VARCHAR(20) NOT NULL DEFAULT 'RASCUNHO', -- RASCUNHO | CALCULADA | ERRO
  "ORIGEM_LAT"       NUMERIC(16, 12),
  "ORIGEM_LON"       NUMERIC(16, 12),
  "ORIGEM_LABEL"     VARCHAR(200),
  "RETORNA_ORIGEM"   CHAR(1) NOT NULL DEFAULT 'S' CHECK ("RETORNA_ORIGEM" IN ('S', 'N')),
  "DISTANCIA_M"      INTEGER,
  "DURACAO_S"        INTEGER,
  "COORDS_OSRM"      TEXT,
  "OSRM_JSON"        JSONB,
  "ERRO_TEXTO"       TEXT,
  "DH_CRIACAO"       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "DH_MAINTENANCE"   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER"          VARCHAR(120)
);

CREATE INDEX IF NOT EXISTS "IX_WMS_CARGA_ROTA_OP_CARGA"
  ON "WMS_CARGA_ROTA_OPERACIONAL" ("TENANT_ID", "CD_CARGA", "VERSAO" DESC);

CREATE TABLE IF NOT EXISTS "WMS_CARGA_ROTA_PARADA" (
  "CD_ROTA_PARADA"   BIGSERIAL PRIMARY KEY,
  "TENANT_ID"        VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_ROTA_OPER"     BIGINT NOT NULL REFERENCES "WMS_CARGA_ROTA_OPERACIONAL" ("CD_ROTA_OPER") ON DELETE CASCADE,
  "ORDEM"            INTEGER NOT NULL,
  "CD_NFE_SAIDA"     INTEGER REFERENCES "WMS_NFE_SAIDA" ("CD_NFE_SAIDA") ON DELETE SET NULL,
  "CHAVE_NFE"        VARCHAR(60),
  "CNPJ_ENTREGA"     VARCHAR(14),
  "NM_ENTREGA"       VARCHAR(200),
  "UF"               VARCHAR(2),
  "NM_MUNICIPIO"     VARCHAR(120),
  "CEP"              VARCHAR(16),
  "LOGRADOURO"       VARCHAR(200),
  "NUMERO"           VARCHAR(30),
  "LATITUDE"         NUMERIC(16, 12),
  "LONGITUDE"        NUMERIC(16, 12),
  "CD_END_ENTREGA"   INTEGER REFERENCES "CADASTRO_ENDERECO_ENTREGA" ("CD_ENDERECO_ENTREGA") ON DELETE SET NULL,
  "MATCH_STATUS"     VARCHAR(30) NOT NULL DEFAULT 'PENDENTE', -- OK | PENDENTE | AMBIGUO
  "DH_CRIACAO"       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS "IX_WMS_CARGA_ROTA_PARADA_ROTA"
  ON "WMS_CARGA_ROTA_PARADA" ("TENANT_ID", "CD_ROTA_OPER", "ORDEM");

COMMENT ON TABLE "WMS_CARGA_ROTA_OPERACIONAL" IS 'Planejamento de rota (OSRM) por carga programada; não substitui roteiros cadastrados.';
COMMENT ON TABLE "WMS_CARGA_ROTA_PARADA" IS 'Paradas da rota operacional (normalmente derivadas das NF-e + match com endereços de entrega).';
