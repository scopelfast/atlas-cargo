-- Pontos de entrega por cliente (CNPJ matriz em CADASTROGERAL).
-- Permite vários endereços por CNPJ sem violar UK_CADASTROGERAL_TENANT_CGCCPF.
-- PostgreSQL, idempotente.

CREATE TABLE IF NOT EXISTS "CADASTRO_ENDERECO_ENTREGA" (
  "CD_ENDERECO_ENTREGA" SERIAL PRIMARY KEY,
  "TENANT_ID"           VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_CLIENTE"         INTEGER NOT NULL,
  "CHAVE_IMPORT"       VARCHAR(64) NOT NULL,
  "DS_PONTO_ENTREGA"   VARCHAR(200) NOT NULL,
  "UF_ENTREGA"         VARCHAR(2),
  "NM_MUNICIPIO"       VARCHAR(120),
  "CEP"                VARCHAR(16),
  "LOGRADOURO"         VARCHAR(200),
  "NUMERO"             VARCHAR(30),
  "COMPLEMENTO"        VARCHAR(120),
  "LATITUDE"           NUMERIC(16, 12),
  "LONGITUDE"          NUMERIC(16, 12),
  "NR_ROTA"            INTEGER,
  "CDCIDADE"           INTEGER,
  "FGACTIVE"           CHAR(1) NOT NULL DEFAULT 'A',
  "DH_INCLUSAO"        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "DH_MAINTENANCE"     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SGUSER"             VARCHAR(64),
  CONSTRAINT "FK_CAD_END_ENT_CLIENTE"
    FOREIGN KEY ("CD_CLIENTE") REFERENCES "CADASTROGERAL" ("CDCADASTRO") ON DELETE CASCADE,
  CONSTRAINT "FK_CAD_END_ENT_CIDADE"
    FOREIGN KEY ("CDCIDADE") REFERENCES "CIDADE" ("CDCIDADE") ON DELETE SET NULL,
  CONSTRAINT "CHK_CAD_END_ENT_FGACTIVE" CHECK ("FGACTIVE" IN ('A', 'I'))
);

CREATE UNIQUE INDEX IF NOT EXISTS "UK_CAD_END_ENT_TENANT_CHAVE"
  ON "CADASTRO_ENDERECO_ENTREGA" ("TENANT_ID", "CHAVE_IMPORT");

CREATE INDEX IF NOT EXISTS "IX_CAD_END_ENT_TENANT_CLIENTE"
  ON "CADASTRO_ENDERECO_ENTREGA" ("TENANT_ID", "CD_CLIENTE");

COMMENT ON TABLE "CADASTRO_ENDERECO_ENTREGA" IS 'Endereços de entrega (pontos) vinculados ao cadastro matriz do cliente (CD_CLIENTE = CDCADASTRO).';
COMMENT ON COLUMN "CADASTRO_ENDERECO_ENTREGA"."CHAVE_IMPORT" IS 'Chave estável para reimportação (hash tenant+cnpj+ponto+logradouro+número+cep).';
