  AND ("CODIGO_MODULO_LICENCA" IS NULL OR TRIM("CODIGO_MODULO_LICENCA") = '');

UPDATE "TIPOATIVIDADE" SET "CODIGO_MODULO_LICENCA" = 'convocacoes'
WHERE LOWER(TRIM("DSPROGRAMA")) IN ('relatorio-convocacoes', 'relatório-convocacoes')
