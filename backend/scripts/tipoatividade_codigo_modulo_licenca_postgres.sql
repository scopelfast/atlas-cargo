-- Catálogo: convocações (relatório + APIs futuras)
INSERT INTO "SAAS_MODULO" ("CODIGO", "NM_EXIBICAO", "ORDEM", "FGACTIVE")
VALUES ('convocacoes', 'Convocações', 6, 'S')
ON CONFLICT ("CODIGO") DO UPDATE SET
  "NM_EXIBICAO" = EXCLUDED."NM_EXIBICAO",
  "ORDEM" = EXCLUDED."ORDEM";

INSERT INTO "SAAS_PLANO_MODULO" ("CD_PLANO", "CODIGO_MODULO")
SELECT 1, 'convocacoes'
WHERE EXISTS (SELECT 1 FROM "SAAS_PLANO" WHERE "CD_PLANO" = 1)
  AND NOT EXISTS (
    SELECT 1 FROM "SAAS_PLANO_MODULO" WHERE "CD_PLANO" = 1 AND "CODIGO_MODULO" = 'convocacoes'
  );

-- Preencher por DSPROGRAMA (ajuste se seus paths forem diferentes)
UPDATE "TIPOATIVIDADE" SET "CODIGO_MODULO_LICENCA" = 'alertas'
WHERE LOWER(TRIM("DSPROGRAMA")) = 'alertas' AND ("CODIGO_MODULO_LICENCA" IS NULL OR TRIM("CODIGO_MODULO_LICENCA") = '');

UPDATE "TIPOATIVIDADE" SET "CODIGO_MODULO_LICENCA" = 'chat'
WHERE LOWER(TRIM("DSPROGRAMA")) = 'chat' AND ("CODIGO_MODULO_LICENCA" IS NULL OR TRIM("CODIGO_MODULO_LICENCA") = '');

UPDATE "TIPOATIVIDADE" SET "CODIGO_MODULO_LICENCA" = 'sos'
WHERE LOWER(TRIM("DSPROGRAMA")) = 'sos' AND ("CODIGO_MODULO_LICENCA" IS NULL OR TRIM("CODIGO_MODULO_LICENCA") = '');

UPDATE "TIPOATIVIDADE" SET "CODIGO_MODULO_LICENCA" = 'ranking'
WHERE LOWER(TRIM("DSPROGRAMA")) = 'ranking' AND ("CODIGO_MODULO_LICENCA" IS NULL OR TRIM("CODIGO_MODULO_LICENCA") = '');

UPDATE "TIPOATIVIDADE" SET "CODIGO_MODULO_LICENCA" = 'mapa_viagem'
