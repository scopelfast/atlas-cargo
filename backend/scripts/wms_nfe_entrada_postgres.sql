-- WMS — importação NF-e (entrada): cabeçalho + linhas em JSONB.
-- PostgreSQL, idempotente (CREATE IF NOT EXISTS).
-- Executar depois de wms_cadastros_mestre_postgres.sql (FK opcional em "CD_DONO").

CREATE TABLE IF NOT EXISTS "WMS_NFE_ENTRADA" (
  "CD_NFE" SERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_DONO" INTEGER REFERENCES "WMS_DONO_ESTOQUE" ("CD_DONO") ON DELETE SET NULL,
  "CHAVE_NFE" CHAR(44) NOT NULL,
  "NUMERO_NF" VARCHAR(20),
  "SERIE" VARCHAR(15),
  "DH_EMISSAO" TIMESTAMPTZ,
  "CNPJ_EMITENTE" VARCHAR(14),
  "XNOME_EMIT" VARCHAR(255),
  "CNPJ_DEST" VARCHAR(14),
  "XNOME_DEST" VARCHAR(255),
  "Q_ITENS" INTEGER NOT NULL DEFAULT 0,
  "LINHAS_JSON" JSONB,
  "CONFERENCIA_JSON" JSONB,
  "FG_CONFERIDO" CHAR(1) NOT NULL DEFAULT 'N',
  "DH_CONFERENCIA" TIMESTAMPTZ,
  "DH_IMPORTACAO" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64),
  "SG_USER_CONFERENCIA" VARCHAR(64),
  "ST_RECEBIMENTO" VARCHAR(20) NOT NULL DEFAULT 'ABERTA',
  "DH_ENCERRAMENTO" TIMESTAMPTZ,
  "SG_USER_ENCERRAMENTO" VARCHAR(64),
  "DH_REABERTURA" TIMESTAMPTZ,
  "SG_USER_REABERTURA" VARCHAR(64),
  "DS_MOTIVO_REABERTURA" VARCHAR(255),
  "DT_RECEBIMENTO" DATE
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_wms_nfe_entrada_tenant_chave
  ON "WMS_NFE_ENTRADA" ("TENANT_ID", "CHAVE_NFE");

CREATE INDEX IF NOT EXISTS idx_wms_nfe_entrada_tenant_dh ON "WMS_NFE_ENTRADA" ("TENANT_ID", "DH_IMPORTACAO" DESC);
CREATE INDEX IF NOT EXISTS idx_wms_nfe_entrada_tenant_dono ON "WMS_NFE_ENTRADA" ("TENANT_ID", "CD_DONO");

-- Evolução idempotente para bases existentes
ALTER TABLE "WMS_NFE_ENTRADA"
  ADD COLUMN IF NOT EXISTS "CONFERENCIA_JSON" JSONB,
  ADD COLUMN IF NOT EXISTS "FG_CONFERIDO" CHAR(1) NOT NULL DEFAULT 'N',
  ADD COLUMN IF NOT EXISTS "DH_CONFERENCIA" TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS "SG_USER_CONFERENCIA" VARCHAR(64),
  ADD COLUMN IF NOT EXISTS "NM_CONFERENTE" VARCHAR(120),
  ADD COLUMN IF NOT EXISTS "ST_RECEBIMENTO" VARCHAR(20) NOT NULL DEFAULT 'ABERTA',
  ADD COLUMN IF NOT EXISTS "DH_ENCERRAMENTO" TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS "SG_USER_ENCERRAMENTO" VARCHAR(64),
  ADD COLUMN IF NOT EXISTS "DH_REABERTURA" TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS "SG_USER_REABERTURA" VARCHAR(64),
  ADD COLUMN IF NOT EXISTS "DS_MOTIVO_REABERTURA" VARCHAR(255),
  ADD COLUMN IF NOT EXISTS "DT_RECEBIMENTO" DATE;
