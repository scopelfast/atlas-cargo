-- WMS — Código operacional (CDPRODUTO) → produto estoque (CDPRODESTO / WMS_PRODUTO_DONO).
-- Estoque, inventário, OPL e reservas usam sempre CD_PRODUTO do SKU de estoque.
-- Planilha OL: CDNVPRODUTO=5, CDPRODUTO operacional, CDPRODESTO canônico, VRFATOCONV / VRARREDEMPPR.
-- PostgreSQL, idempotente. Executar após wms_produtos_dono_postgres.sql

CREATE TABLE IF NOT EXISTS "WMS_PRODUTO_OPERACIONAL" (
  "CD_OPERACIONAL" SERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_DONO" INTEGER NOT NULL REFERENCES "WMS_DONO_ESTOQUE" ("CD_DONO") ON DELETE RESTRICT,
  "CD_PRODUTO" INTEGER NOT NULL REFERENCES "WMS_PRODUTO_DONO" ("CD_PRODUTO") ON DELETE CASCADE,
  "CODIGO_OPERACIONAL" VARCHAR(128) NOT NULL,
  "CODIGO_ESTOQUE" VARCHAR(128) NOT NULL,
  "UNIDADE" VARCHAR(10),
  "FATOR_CONVERSAO" NUMERIC(18, 6) NOT NULL DEFAULT 1,
  "INDICE_ARRED" NUMERIC(18, 6),
  "NIVEL_OL" SMALLINT,
  "FGACTIVE" CHAR(1) NOT NULL DEFAULT 'S',
  "DH_MAINTENANCE" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64),
  CONSTRAINT chk_wms_prod_op_fg CHECK ("FGACTIVE" IN ('S', 'N')),
  CONSTRAINT chk_wms_prod_op_fator CHECK ("FATOR_CONVERSAO" > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_wms_prod_op_tenant_dono_codop
  ON "WMS_PRODUTO_OPERACIONAL" ("TENANT_ID", "CD_DONO", LOWER(TRIM("CODIGO_OPERACIONAL")));

CREATE INDEX IF NOT EXISTS idx_wms_prod_op_tenant_dono_estoque
  ON "WMS_PRODUTO_OPERACIONAL" ("TENANT_ID", "CD_DONO", LOWER(TRIM("CODIGO_ESTOQUE")));

CREATE INDEX IF NOT EXISTS idx_wms_prod_op_cd_produto
  ON "WMS_PRODUTO_OPERACIONAL" ("CD_PRODUTO");

COMMENT ON TABLE "WMS_PRODUTO_OPERACIONAL" IS 'De-para interno OL: CDPRODUTO (UM operacional) → CD_PRODUTO estoque (CDPRODESTO mascarado). Movimentação sempre no CD_PRODUTO.';
COMMENT ON COLUMN "WMS_PRODUTO_OPERACIONAL"."CODIGO_ESTOQUE" IS 'CDPRODESTO (texto canônico de estoque, com máscara do dono).';
COMMENT ON COLUMN "WMS_PRODUTO_OPERACIONAL"."INDICE_ARRED" IS 'VRARREDEMPPR da planilha OL (índice de arredondamento / embalagem).';
