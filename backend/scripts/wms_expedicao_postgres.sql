-- WMS — Expedição (execução da saída da carga)
-- Execute após: backend/scripts/wms_carga_programada_postgres.sql

CREATE TABLE IF NOT EXISTS "WMS_EXPEDICAO_CARGA" (
  "CD_CARGA" INTEGER PRIMARY KEY REFERENCES "WMS_CARGA_PROGRAMADA"("CD_CARGA") ON DELETE CASCADE,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "ST_EXPEDICAO" VARCHAR(24) NOT NULL DEFAULT 'PRONTA_EXPEDICAO',
  "DH_INICIO" TIMESTAMPTZ,
  "DH_SAIDA" TIMESTAMPTZ,
  "NM_CONFERENTE" VARCHAR(120),
  "NM_MOTORISTA" VARCHAR(120),
  "PLACA" VARCHAR(10),
  "OBS" TEXT,
  "DH_MAINTENANCE" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64)
);

CREATE INDEX IF NOT EXISTS idx_wms_expedicao_tenant_status
  ON "WMS_EXPEDICAO_CARGA" ("TENANT_ID", "ST_EXPEDICAO");

