-- WMS — Lotes de crossdocking (fase 1): agrupamento de NF-e por operação de expedição.
-- PostgreSQL, idempotente.

CREATE TABLE IF NOT EXISTS "WMS_CROSSDOCK_LOTE" (
  "CD_LOTE" SERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CODIGO" VARCHAR(40) NOT NULL,
  "NOME" VARCHAR(120),
  "FASE" VARCHAR(20) NOT NULL DEFAULT 'RECEBIMENTO',
  "DH_JANELA_EXPEDICAO" TIMESTAMPTZ,
  "OBSERVACAO" VARCHAR(255),
  "FGACTIVE" CHAR(1) NOT NULL DEFAULT 'S',
  "DH_CRIACAO" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "DH_MAINTENANCE" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64),
  CONSTRAINT "ck_wms_crossdock_lote_fase"
    CHECK ("FASE" IN ('RECEBIMENTO', 'SEPARACAO', 'PRE_EMBARQUE', 'EMBARCADO', 'ENCERRADO'))
);

CREATE UNIQUE INDEX IF NOT EXISTS "uk_wms_crossdock_lote_tenant_codigo"
  ON "WMS_CROSSDOCK_LOTE" ("TENANT_ID", "CODIGO");

CREATE INDEX IF NOT EXISTS "idx_wms_crossdock_lote_tenant_fase"
  ON "WMS_CROSSDOCK_LOTE" ("TENANT_ID", "FASE", "DH_CRIACAO" DESC);

CREATE TABLE IF NOT EXISTS "WMS_CROSSDOCK_LOTE_NFE" (
  "CD_LOTE" INTEGER NOT NULL REFERENCES "WMS_CROSSDOCK_LOTE" ("CD_LOTE") ON DELETE CASCADE,
  "CD_NFE" INTEGER NOT NULL REFERENCES "WMS_NFE_ENTRADA" ("CD_NFE") ON DELETE CASCADE,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "DH_VINCULO" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64),
  PRIMARY KEY ("CD_LOTE", "CD_NFE")
);

CREATE INDEX IF NOT EXISTS "idx_wms_crossdock_lote_nfe_tenant_lote"
  ON "WMS_CROSSDOCK_LOTE_NFE" ("TENANT_ID", "CD_LOTE");

CREATE INDEX IF NOT EXISTS "idx_wms_crossdock_lote_nfe_tenant_nfe"
  ON "WMS_CROSSDOCK_LOTE_NFE" ("TENANT_ID", "CD_NFE");
