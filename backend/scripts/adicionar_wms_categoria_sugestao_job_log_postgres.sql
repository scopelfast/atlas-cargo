-- Histórico de execuções do job de categoria automática (alta confiança).
-- Rode no PostgreSQL do tenant Atlas Cargo.

CREATE TABLE IF NOT EXISTS "WMS_CATEGORIA_SUGESTAO_JOB_LOG" (
  "CD_LOG" SERIAL PRIMARY KEY,
  "DH_EXECUCAO" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "TENANT_ID" VARCHAR(64) NOT NULL,
  "CD_DONO" INTEGER NULL,
  "NU_CANDIDATOS" INTEGER NOT NULL DEFAULT 0,
  "NU_ATUALIZADOS" INTEGER NOT NULL DEFAULT 0,
  "ST_DRY_RUN" CHAR(1) NOT NULL DEFAULT 'N',
  "DS_DETALHE" VARCHAR(800) NULL,
  "DS_RESUMO_JSON" JSONB NULL
);

CREATE INDEX IF NOT EXISTS "IX_WMS_CAT_SUG_JOB_LOG_TENANT_DH"
  ON "WMS_CATEGORIA_SUGESTAO_JOB_LOG" ("TENANT_ID", "DH_EXECUCAO" DESC);

COMMENT ON TABLE "WMS_CATEGORIA_SUGESTAO_JOB_LOG" IS
  'Log do job que aplica categoria em produtos sem CD_CATEGORIA (somente confiança alta; escopo dono+conservação).';
