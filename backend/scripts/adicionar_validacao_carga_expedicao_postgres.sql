-- adicionar_validacao_carga_expedicao_postgres.sql
-- Objetivo: criar estrutura de separacao e validacao de carga x NF-e para bloquear divergencias antes da expedicao.
-- Executar no pgAdmin, banco atlas_cargo_prd (PostgreSQL).

CREATE TABLE IF NOT EXISTS "WMS_SEPARACAO_PEDIDO_ITEM" (
  "CD_SEPARACAO_ITEM" BIGSERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_CARGA" INTEGER REFERENCES "WMS_CARGA_PROGRAMADA" ("CD_CARGA") ON DELETE CASCADE,
  "NR_PEDIDO" VARCHAR(20) NOT NULL,
  "COD_PRODUTO" VARCHAR(30) NOT NULL,
  "DS_PRODUTO" VARCHAR(255),
  "UNIDADE" VARCHAR(12),
  "QTD_SEPARADA" NUMERIC(18,4) NOT NULL DEFAULT 0,
  "ORIGEM_ARQUIVO" VARCHAR(255),
  "DH_IMPORTACAO" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64)
);

CREATE INDEX IF NOT EXISTS "idx_wms_sep_item_tenant_carga"
  ON "WMS_SEPARACAO_PEDIDO_ITEM" ("TENANT_ID", "CD_CARGA");

CREATE INDEX IF NOT EXISTS "idx_wms_sep_item_tenant_pedido"
  ON "WMS_SEPARACAO_PEDIDO_ITEM" ("TENANT_ID", "NR_PEDIDO");

CREATE INDEX IF NOT EXISTS "idx_wms_sep_item_tenant_pedido_prod"
  ON "WMS_SEPARACAO_PEDIDO_ITEM" ("TENANT_ID", "NR_PEDIDO", "COD_PRODUTO");

CREATE TABLE IF NOT EXISTS "WMS_CARGA_VALIDACAO" (
  "CD_VALIDACAO" BIGSERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_CARGA" INTEGER NOT NULL REFERENCES "WMS_CARGA_PROGRAMADA" ("CD_CARGA") ON DELETE CASCADE,
  "ST_VALIDACAO" VARCHAR(20) NOT NULL,
  "QT_FALTAS" INTEGER NOT NULL DEFAULT 0,
  "QT_SOBRAS" INTEGER NOT NULL DEFAULT 0,
  "QT_INVERSOES" INTEGER NOT NULL DEFAULT 0,
  "QT_SEM_PEDIDO" INTEGER NOT NULL DEFAULT 0,
  "QT_SEM_NF" INTEGER NOT NULL DEFAULT 0,
  "GERADO_EM" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64)
);

CREATE INDEX IF NOT EXISTS "idx_wms_carga_validacao_tenant_carga"
  ON "WMS_CARGA_VALIDACAO" ("TENANT_ID", "CD_CARGA", "GERADO_EM" DESC);

CREATE TABLE IF NOT EXISTS "WMS_CARGA_VALIDACAO_ITEM" (
  "CD_VALIDACAO_ITEM" BIGSERIAL PRIMARY KEY,
  "CD_VALIDACAO" BIGINT NOT NULL REFERENCES "WMS_CARGA_VALIDACAO" ("CD_VALIDACAO") ON DELETE CASCADE,
  "NR_PEDIDO" VARCHAR(20),
  "COD_PRODUTO" VARCHAR(30),
  "DS_PRODUTO" VARCHAR(255),
  "UNIDADE_PEDIDO" VARCHAR(12),
  "UNIDADE_NF" VARCHAR(12),
  "QTD_PEDIDO" NUMERIC(18,4) NOT NULL DEFAULT 0,
  "QTD_NF" NUMERIC(18,4) NOT NULL DEFAULT 0,
  "QTD_DIF" NUMERIC(18,4) NOT NULL DEFAULT 0,
  "TP_DIVERGENCIA" VARCHAR(30) NOT NULL,
  "SEVERIDADE" VARCHAR(20) NOT NULL DEFAULT 'BLOQUEIO'
);

CREATE INDEX IF NOT EXISTS "idx_wms_carga_validacao_item_cd_validacao"
  ON "WMS_CARGA_VALIDACAO_ITEM" ("CD_VALIDACAO");
