-- Atlas Pay Fase 3 — fechamento periódico do uso da plataforma.
-- Idempotente. Não altera P0/P1/P2 nem constraints existentes de CONEXAO.
-- Aditivo: tabelas FIN_FECHAMENTO_USO* + índice único de cobrança USO por ciclo.

BEGIN;

CREATE TABLE IF NOT EXISTS "FIN_FECHAMENTO_USO" (
  "ID" bigserial PRIMARY KEY,
  "TENANT_ID" varchar(64) NOT NULL,
  "COMPETENCIA" char(7) NOT NULL,
  "STATUS" varchar(40) NOT NULL,
  "TOTAL_CENTAVOS" bigint NOT NULL DEFAULT 0,
  "QTD_ANUNCIADAS" integer NOT NULL DEFAULT 0,
  "QTD_VALIDAS" integer NOT NULL DEFAULT 0,
  "QTD_FRETE_INVALIDO" integer NOT NULL DEFAULT 0,
  "BASE_PERCENTUAL" numeric(18, 4) NOT NULL DEFAULT 0,
  "FG_REGRA_SNAPSHOT" char(1) NOT NULL DEFAULT 'N',
  "CODIGO_RESULTADO" varchar(60) NULL,
  "MEMORIA_CALCULO" text NOT NULL,
  "EXCECOES" text NULL,
  "ID_CICLO_USO" varchar(64) NOT NULL,
  "ID_COBRANCA" bigint NULL,
  "VERSAO_CALCULO" integer NOT NULL DEFAULT 1,
  "DH_CRIACAO" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SGUSER_CRIACAO" varchar(50) NULL,
  "DH_RECALCULO" timestamp NULL,
  "SGUSER_RECALCULO" varchar(50) NULL,
  "DH_APROVACAO" timestamp NULL,
  "SGUSER_APROVACAO" varchar(50) NULL,
  "DH_VENCIMENTO" timestamp NULL,
  "DH_COBRANCA" timestamp NULL,
  "SGUSER_COBRANCA" varchar(50) NULL,
  CONSTRAINT "CK_FIN_FECH_STATUS" CHECK ("STATUS" IN (
    'RASCUNHO',
    'COM_EXCECOES',
    'AGUARDANDO_APROVACAO',
    'APROVADO',
    'COBRADO',
    'SEM_COMPONENTE_USO_PLATAFORMA'
  )),
  CONSTRAINT "CK_FIN_FECH_COMP" CHECK ("COMPETENCIA" ~ '^[0-9]{4}-[0-9]{2}$'),
  CONSTRAINT "CK_FIN_FECH_TOTAL" CHECK ("TOTAL_CENTAVOS" >= 0),
  CONSTRAINT "CK_FIN_FECH_REGRA" CHECK ("FG_REGRA_SNAPSHOT" IN ('S', 'N')),
  CONSTRAINT "FK_FIN_FECH_TENANT" FOREIGN KEY ("TENANT_ID")
    REFERENCES "SAAS_CLIENTE_CONTRATANTE" ("TENANT_ID"),
  CONSTRAINT "FK_FIN_FECH_COB" FOREIGN KEY ("ID_COBRANCA")
    REFERENCES "FIN_COBRANCA" ("ID") ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS "UK_FIN_FECH_TENANT_COMP"
  ON "FIN_FECHAMENTO_USO" ("TENANT_ID", "COMPETENCIA");

CREATE UNIQUE INDEX IF NOT EXISTS "UK_FIN_FECH_CICLO"
  ON "FIN_FECHAMENTO_USO" ("ID_CICLO_USO");

CREATE INDEX IF NOT EXISTS "IX_FIN_FECH_STATUS"
  ON "FIN_FECHAMENTO_USO" ("TENANT_ID", "STATUS", "COMPETENCIA" DESC);

CREATE TABLE IF NOT EXISTS "FIN_FECHAMENTO_USO_EVENTO" (
  "ID" bigserial PRIMARY KEY,
  "ID_FECHAMENTO" bigint NOT NULL,
  "TIPO" varchar(40) NOT NULL,
  "STATUS_ANTERIOR" varchar(40) NULL,
  "STATUS_NOVO" varchar(40) NULL,
  "SGUSER" varchar(50) NULL,
  "DH_EVENTO" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "DETALHE" varchar(500) NULL,
  "IP" varchar(64) NULL,
  CONSTRAINT "FK_FIN_FECH_EVT" FOREIGN KEY ("ID_FECHAMENTO")
    REFERENCES "FIN_FECHAMENTO_USO" ("ID") ON DELETE RESTRICT,
  CONSTRAINT "CK_FIN_FECH_EVT_TIPO" CHECK ("TIPO" IN (
    'CRIADO', 'RECALCULADO', 'APROVADO', 'COBRANCA_GERADA', 'BLOQUEADO'
  ))
);

CREATE INDEX IF NOT EXISTS "IX_FIN_FECH_EVT"
  ON "FIN_FECHAMENTO_USO_EVENTO" ("ID_FECHAMENTO", "DH_EVENTO");

-- Idempotência: no máximo uma cobrança USO ativa (ABERTA/PAGA) por ciclo sintético.
CREATE UNIQUE INDEX IF NOT EXISTS "UK_FIN_COB_USO_CICLO_ATIVA"
  ON "FIN_COBRANCA" ("TENANT_ID", "ID_CICLO_CONFIRMACAO")
  WHERE "MODALIDADE" = 'USO_PLATAFORMA'
    AND "STATUS" IN ('ABERTA', 'PAGA');

COMMIT;
