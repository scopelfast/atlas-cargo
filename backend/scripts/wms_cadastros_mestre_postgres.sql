-- WMS — cadastros mestre (dono do estoque, armazém, área, doca).
-- PostgreSQL, idempotente. Executar após backup.
-- Relacionado: docs/PLANO_ESTOQUE_TERCEIROS_E_CROSSDOCKING_ATLAS_CARGO.md §5.1

CREATE TABLE IF NOT EXISTS "WMS_DONO_ESTOQUE" (
  "CD_DONO" SERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CODIGO" VARCHAR(32) NOT NULL,
  "NOME" VARCHAR(160) NOT NULL,
  "CGC" VARCHAR(14),
  "MASCARA_CODIGO_PRODUTO" VARCHAR(40),
  "FGACTIVE" CHAR(1) NOT NULL DEFAULT 'S',
  "DH_MAINTENANCE" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64),
  CONSTRAINT chk_wms_dono_fgactive CHECK ("FGACTIVE" IN ('S', 'N'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_wms_dono_tenant_codigo
  ON "WMS_DONO_ESTOQUE" ("TENANT_ID", LOWER(TRIM("CODIGO")));

CREATE INDEX IF NOT EXISTS idx_wms_dono_tenant ON "WMS_DONO_ESTOQUE" ("TENANT_ID");

CREATE TABLE IF NOT EXISTS "WMS_ARMAZEM" (
  "CD_ARMAZEM" SERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_DONO" INTEGER NOT NULL REFERENCES "WMS_DONO_ESTOQUE" ("CD_DONO") ON DELETE RESTRICT,
  "CODIGO" VARCHAR(32) NOT NULL,
  "NOME" VARCHAR(160) NOT NULL,
  "FGACTIVE" CHAR(1) NOT NULL DEFAULT 'S',
  "DH_MAINTENANCE" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64),
  CONSTRAINT chk_wms_armazem_fgactive CHECK ("FGACTIVE" IN ('S', 'N'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_wms_armazem_tenant_dono_codigo
  ON "WMS_ARMAZEM" ("TENANT_ID", "CD_DONO", LOWER(TRIM("CODIGO")));

CREATE INDEX IF NOT EXISTS idx_wms_armazem_tenant_dono ON "WMS_ARMAZEM" ("TENANT_ID", "CD_DONO");

CREATE TABLE IF NOT EXISTS "WMS_AREA" (
  "CD_AREA" SERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_ARMAZEM" INTEGER NOT NULL REFERENCES "WMS_ARMAZEM" ("CD_ARMAZEM") ON DELETE RESTRICT,
  "CODIGO" VARCHAR(32) NOT NULL,
  "NOME" VARCHAR(160) NOT NULL,
  "FGACTIVE" CHAR(1) NOT NULL DEFAULT 'S',
  "DH_MAINTENANCE" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64),
  CONSTRAINT chk_wms_area_fgactive CHECK ("FGACTIVE" IN ('S', 'N'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_wms_area_tenant_arm_codigo
  ON "WMS_AREA" ("TENANT_ID", "CD_ARMAZEM", LOWER(TRIM("CODIGO")));

CREATE INDEX IF NOT EXISTS idx_wms_area_tenant_arm ON "WMS_AREA" ("TENANT_ID", "CD_ARMAZEM");

CREATE TABLE IF NOT EXISTS "WMS_DOCA" (
  "CD_DOCA" SERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_ARMAZEM" INTEGER NOT NULL REFERENCES "WMS_ARMAZEM" ("CD_ARMAZEM") ON DELETE RESTRICT,
  "CODIGO" VARCHAR(32) NOT NULL,
  "NOME" VARCHAR(160) NOT NULL,
  "FG_RECEBE" CHAR(1) NOT NULL DEFAULT 'S',
  "FG_EXPEDE" CHAR(1) NOT NULL DEFAULT 'S',
  "FGACTIVE" CHAR(1) NOT NULL DEFAULT 'S',
  "DH_MAINTENANCE" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64),
  CONSTRAINT chk_wms_doca_fgactive CHECK ("FGACTIVE" IN ('S', 'N')),
  CONSTRAINT chk_wms_doca_recebe CHECK ("FG_RECEBE" IN ('S', 'N')),
  CONSTRAINT chk_wms_doca_expede CHECK ("FG_EXPEDE" IN ('S', 'N'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_wms_doca_tenant_arm_codigo
  ON "WMS_DOCA" ("TENANT_ID", "CD_ARMAZEM", LOWER(TRIM("CODIGO")));

CREATE INDEX IF NOT EXISTS idx_wms_doca_tenant_arm ON "WMS_DOCA" ("TENANT_ID", "CD_ARMAZEM");

-- Agrupamento logístico para separação/picking
CREATE TABLE IF NOT EXISTS "WMS_GRUPO_PRODUTO" (
  "CD_GRUPO" SERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CODIGO" VARCHAR(32) NOT NULL,
  "NOME" VARCHAR(120) NOT NULL,
  "ORDEM" INTEGER NOT NULL DEFAULT 0,
  "FGACTIVE" CHAR(1) NOT NULL DEFAULT 'S',
  "DH_MAINTENANCE" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64),
  CONSTRAINT chk_wms_grupo_fgactive CHECK ("FGACTIVE" IN ('S', 'N'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_wms_grupo_tenant_codigo
  ON "WMS_GRUPO_PRODUTO" ("TENANT_ID", LOWER(TRIM("CODIGO")));

CREATE INDEX IF NOT EXISTS idx_wms_grupo_tenant_nome
  ON "WMS_GRUPO_PRODUTO" ("TENANT_ID", LOWER("NOME"));

-- Categoria de produto (subnível de grupo)
CREATE TABLE IF NOT EXISTS "WMS_CATEGORIA_PRODUTO" (
  "CD_CATEGORIA" SERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_GRUPO" INTEGER NOT NULL REFERENCES "WMS_GRUPO_PRODUTO" ("CD_GRUPO") ON DELETE RESTRICT,
  "CODIGO" VARCHAR(32) NOT NULL,
  "NOME" VARCHAR(120) NOT NULL,
  "ORDEM" INTEGER NOT NULL DEFAULT 0,
  "FGACTIVE" CHAR(1) NOT NULL DEFAULT 'S',
  "DH_MAINTENANCE" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64),
  CONSTRAINT chk_wms_categoria_fgactive CHECK ("FGACTIVE" IN ('S', 'N'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_wms_categoria_tenant_grupo_codigo
  ON "WMS_CATEGORIA_PRODUTO" ("TENANT_ID", "CD_GRUPO", LOWER(TRIM("CODIGO")));

CREATE INDEX IF NOT EXISTS idx_wms_categoria_tenant_grupo_nome
  ON "WMS_CATEGORIA_PRODUTO" ("TENANT_ID", "CD_GRUPO", LOWER("NOME"));
