-- WMS — cadastro mestre de produtos por dono do estoque.
-- PostgreSQL, idempotente. Executar após:
--   1) backend/scripts/wms_cadastros_mestre_postgres.sql
--   2) backend/scripts/wms_depara_produto_postgres.sql (opcional, mas recomendado)

CREATE TABLE IF NOT EXISTS "WMS_PRODUTO_DONO" (
  "CD_PRODUTO" SERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_DONO" INTEGER NOT NULL REFERENCES "WMS_DONO_ESTOQUE" ("CD_DONO") ON DELETE RESTRICT,
  "CD_CATEGORIA" INTEGER REFERENCES "WMS_CATEGORIA_PRODUTO" ("CD_CATEGORIA") ON DELETE SET NULL,
  "CODIGO" VARCHAR(128) NOT NULL,
  "NOME" VARCHAR(200) NOT NULL,
  "UNIDADE" VARCHAR(10),
  "CODIGO_BARRAS" VARCHAR(32),
  "NCM" VARCHAR(8),
  "PESO_KG" NUMERIC(12,3),
  "TIPO_ARMAZENAGEM" VARCHAR(20),
  "ORIGEM_CADASTRO" VARCHAR(24) NOT NULL DEFAULT 'MANUAL',
  "FG_FORNECEDOR_REF" CHAR(1) NOT NULL DEFAULT 'N',
  "FG_DESCARTAVEL" CHAR(1) NOT NULL DEFAULT 'N',
  "FG_CONTROLA_LOTE" CHAR(1) NOT NULL DEFAULT 'N',
  "FG_CONTROLA_VALIDADE" CHAR(1) NOT NULL DEFAULT 'N',
  "FGACTIVE" CHAR(1) NOT NULL DEFAULT 'S',
  "DH_MAINTENANCE" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64),
  CONSTRAINT chk_wms_produto_origem CHECK ("ORIGEM_CADASTRO" IN ('MANUAL', 'IMPORT_XML_PRODUTO', 'NF_ENTRADA_AUTO')),
  CONSTRAINT chk_wms_produto_fg_forn_ref CHECK ("FG_FORNECEDOR_REF" IN ('S', 'N')),
  CONSTRAINT chk_wms_produto_fgactive CHECK ("FGACTIVE" IN ('S', 'N')),
  CONSTRAINT chk_wms_produto_fg_desc CHECK ("FG_DESCARTAVEL" IN ('S', 'N')),
  CONSTRAINT chk_wms_produto_fg_lote CHECK ("FG_CONTROLA_LOTE" IN ('S', 'N')),
  CONSTRAINT chk_wms_produto_fg_val CHECK ("FG_CONTROLA_VALIDADE" IN ('S', 'N'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_wms_produto_tenant_dono_codigo
  ON "WMS_PRODUTO_DONO" ("TENANT_ID", "CD_DONO", LOWER(TRIM("CODIGO")));

CREATE INDEX IF NOT EXISTS idx_wms_produto_tenant_dono
  ON "WMS_PRODUTO_DONO" ("TENANT_ID", "CD_DONO");

CREATE INDEX IF NOT EXISTS idx_wms_produto_tenant_nome
  ON "WMS_PRODUTO_DONO" ("TENANT_ID", LOWER("NOME"));

-- Evolução idempotente para bases já existentes
ALTER TABLE "WMS_DONO_ESTOQUE"
  ADD COLUMN IF NOT EXISTS "MASCARA_CODIGO_PRODUTO" VARCHAR(40);

ALTER TABLE "WMS_PRODUTO_DONO"
  ADD COLUMN IF NOT EXISTS "NCM" VARCHAR(8),
  ADD COLUMN IF NOT EXISTS "PESO_KG" NUMERIC(12,3),
  ADD COLUMN IF NOT EXISTS "TIPO_ARMAZENAGEM" VARCHAR(20),
  ADD COLUMN IF NOT EXISTS "CD_CATEGORIA" INTEGER,
  ADD COLUMN IF NOT EXISTS "ORIGEM_CADASTRO" VARCHAR(24) NOT NULL DEFAULT 'MANUAL',
  ADD COLUMN IF NOT EXISTS "FG_FORNECEDOR_REF" CHAR(1) NOT NULL DEFAULT 'N',
  ADD COLUMN IF NOT EXISTS "FG_DESCARTAVEL" CHAR(1) NOT NULL DEFAULT 'N',
  ADD COLUMN IF NOT EXISTS "FG_CONTROLA_LOTE" CHAR(1) NOT NULL DEFAULT 'N',
  ADD COLUMN IF NOT EXISTS "FG_CONTROLA_VALIDADE" CHAR(1) NOT NULL DEFAULT 'N';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.table_constraints
    WHERE table_name = 'WMS_PRODUTO_DONO'
      AND constraint_name = 'fk_wms_produto_categoria'
  ) THEN
    ALTER TABLE "WMS_PRODUTO_DONO"
      ADD CONSTRAINT fk_wms_produto_categoria
      FOREIGN KEY ("CD_CATEGORIA") REFERENCES "WMS_CATEGORIA_PRODUTO" ("CD_CATEGORIA") ON DELETE SET NULL;
  END IF;
END $$;

-- Índices dependentes de colunas novas (criar após ALTER TABLE)
CREATE INDEX IF NOT EXISTS idx_wms_produto_tenant_categoria
  ON "WMS_PRODUTO_DONO" ("TENANT_ID", "CD_CATEGORIA");

CREATE INDEX IF NOT EXISTS idx_wms_produto_tenant_origem
  ON "WMS_PRODUTO_DONO" ("TENANT_ID", "FG_FORNECEDOR_REF", "ORIGEM_CADASTRO");
