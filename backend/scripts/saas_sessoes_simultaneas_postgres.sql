-- Limite de sessões simultâneas no painel (torre): login em /api/auth/login.
-- Contagem: linhas em USUARIOLOGACESSO com DHLOGOUT IS NULL e DHLOGIN dentro da janela TOWER_SESSION_TTL_HOURS (padrão 8h, alinhada ao JWT).
-- NULL no plano ou override = ilimitado. PostgreSQL. Idempotente.

ALTER TABLE "SAAS_PLANO" ADD COLUMN IF NOT EXISTS "MAX_SESSOES_SIMULTANEAS" integer NULL;
ALTER TABLE "SAAS_CLIENTE_CONTRATANTE" ADD COLUMN IF NOT EXISTS "MAX_SESSOES_SIMULTANEAS_OVR" integer NULL;

COMMENT ON COLUMN "SAAS_PLANO"."MAX_SESSOES_SIMULTANEAS" IS 'Máx. logins simultâneos ao dashboard (torre); NULL = ilimitado.';
COMMENT ON COLUMN "SAAS_CLIENTE_CONTRATANTE"."MAX_SESSOES_SIMULTANEAS_OVR" IS 'Override por tenant; NULL = usar SAAS_PLANO.MAX_SESSOES_SIMULTANEAS.';

CREATE INDEX IF NOT EXISTS "IX_USUARIOLOGACESSO_TORRE_SESSAO"
  ON "USUARIOLOGACESSO" ("TENANT_ID", "DHLOGIN" DESC)
  WHERE "DHLOGOUT" IS NULL;
