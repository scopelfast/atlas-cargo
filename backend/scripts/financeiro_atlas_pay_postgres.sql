-- Atlas Pay — tabelas financeiras (fases 1 e 2).
-- PostgreSQL, idempotente. Não ativa regra para nenhum tenant.
-- Ordem: rodar após saas_estrutura_plano_cliente_modulo_postgres.sql (SAAS_CLIENTE_CONTRATANTE).

-- Contrato versionado por tenant (agenciador). FG_REGRA_ATIVA padrão N.
CREATE TABLE IF NOT EXISTS "FIN_CONTRATO" (
  "ID" bigserial PRIMARY KEY,
  "TENANT_ID" varchar(64) NOT NULL,
  "VERSAO" integer NOT NULL DEFAULT 1,
  "DH_INICIO" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "DH_FIM" timestamp NULL,
  "FG_REGRA_ATIVA" char(1) NOT NULL DEFAULT 'N',
  "POLITICA_INADIMPLENCIA" varchar(20) NOT NULL DEFAULT 'ALERTA',
  "FGACTIVE" char(1) NOT NULL DEFAULT 'S',
  "DHINCLUSAO" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SGUSERINCLUSAO" varchar(50) NULL,
  "DHMAINTENANCE" timestamp NULL,
  "SGUSER" varchar(50) NULL,
  CONSTRAINT "CK_FIN_CONTRATO_REGRA" CHECK ("FG_REGRA_ATIVA" IN ('S', 'N')),
  CONSTRAINT "CK_FIN_CONTRATO_POL" CHECK ("POLITICA_INADIMPLENCIA" IN ('ALERTA', 'BLOQUEIO')),
  CONSTRAINT "CK_FIN_CONTRATO_ACTIVE" CHECK ("FGACTIVE" IN ('S', 'N', 'A', 'I')),
  CONSTRAINT "FK_FIN_CONTRATO_TENANT" FOREIGN KEY ("TENANT_ID")
    REFERENCES "SAAS_CLIENTE_CONTRATANTE" ("TENANT_ID")
);

CREATE UNIQUE INDEX IF NOT EXISTS "UK_FIN_CONTRATO_TENANT_VERSAO"
  ON "FIN_CONTRATO" ("TENANT_ID", "VERSAO");

-- No máximo um contrato vigente (DH_FIM nulo) por tenant.
CREATE UNIQUE INDEX IF NOT EXISTS "UK_FIN_CONTRATO_VIGENTE"
  ON "FIN_CONTRATO" ("TENANT_ID")
  WHERE "DH_FIM" IS NULL AND "FGACTIVE" IN ('S', 'A');

CREATE INDEX IF NOT EXISTS "IX_FIN_CONTRATO_TENANT"
  ON "FIN_CONTRATO" ("TENANT_ID");

-- Componentes: CONEXAO (fixo / percentual) e USO_PLATAFORMA (fixo / por carga / percentual).
CREATE TABLE IF NOT EXISTS "FIN_CONTRATO_COMPONENTE" (
  "ID" bigserial PRIMARY KEY,
  "ID_CONTRATO" bigint NOT NULL,
  "GRUPO" varchar(20) NOT NULL,
  "TIPO" varchar(40) NOT NULL,
  "VALOR_CENTAVOS" bigint NULL,
  "PERCENTUAL" numeric(9, 4) NULL,
  "FG_ATIVO" char(1) NOT NULL DEFAULT 'S',
  "ORDEM" smallint NOT NULL DEFAULT 0,
  "DHINCLUSAO" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SGUSERINCLUSAO" varchar(50) NULL,
  CONSTRAINT "FK_FIN_COMP_CONTRATO" FOREIGN KEY ("ID_CONTRATO")
    REFERENCES "FIN_CONTRATO" ("ID") ON DELETE CASCADE,
  CONSTRAINT "CK_FIN_COMP_GRUPO" CHECK ("GRUPO" IN ('CONEXAO', 'USO_PLATAFORMA')),
  CONSTRAINT "CK_FIN_COMP_TIPO" CHECK ("TIPO" IN (
    'FIXO', 'PERCENTUAL', 'POR_CARGA_ANUNCIADA'
  )),
  CONSTRAINT "CK_FIN_COMP_ATIVO" CHECK ("FG_ATIVO" IN ('S', 'N')),
  CONSTRAINT "CK_FIN_COMP_VALOR" CHECK (
    ("VALOR_CENTAVOS" IS NULL OR "VALOR_CENTAVOS" >= 0)
    AND ("PERCENTUAL" IS NULL OR ("PERCENTUAL" >= 0 AND "PERCENTUAL" <= 100))
  )
);

CREATE INDEX IF NOT EXISTS "IX_FIN_COMP_CONTRATO"
  ON "FIN_CONTRATO_COMPONENTE" ("ID_CONTRATO", "GRUPO");

-- 1 linha por tipo dentro do grupo (fixo + % somam; o mesmo tipo não repete)
CREATE UNIQUE INDEX IF NOT EXISTS "UK_FIN_COMP_CONTRATO_GRUPO_TIPO"
  ON "FIN_CONTRATO_COMPONENTE" ("ID_CONTRATO", "GRUPO", "TIPO");

-- Cobranças. Valor imutável após insert (sem UPDATE de VALOR_CENTAVOS na aplicação).
CREATE TABLE IF NOT EXISTS "FIN_COBRANCA" (
  "ID" bigserial PRIMARY KEY,
  "MODALIDADE" varchar(20) NOT NULL,
  "TENANT_ID" varchar(64) NOT NULL,
  "PAGADOR_TIPO" varchar(20) NOT NULL,
  "PAGADOR_CDCADASTRO" numeric(15, 0) NULL,
  "PAGADOR_TENANT_ID" varchar(64) NULL,
  "BENEFICIARIO_TENANT_ID" varchar(64) NOT NULL,
  "IDVIAGEM" numeric(15, 0) NULL,
  "IDCONVOCACAO" integer NULL,
  "ID_CICLO_CONFIRMACAO" varchar(64) NOT NULL,
  "ID_CONTRATO" bigint NULL,
  "VERSAO_CONTRATO" integer NULL,
  "VALOR_CENTAVOS" bigint NOT NULL,
  "MOEDA" varchar(3) NOT NULL DEFAULT 'BRL',
  "MEMORIA_CALCULO" text NULL,
  "STATUS" varchar(20) NOT NULL DEFAULT 'ABERTA',
  "DH_CRIACAO" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SGUSER_CRIACAO" varchar(50) NULL,
  "DH_VENCIMENTO" timestamp NULL,
  "DH_BAIXA" timestamp NULL,
  "SGUSER_BAIXA" varchar(50) NULL,
  "DS_BAIXA" varchar(400) NULL,
  "DH_CANCELAMENTO" timestamp NULL,
  "SGUSER_CANCELAMENTO" varchar(50) NULL,
  "DS_CANCELAMENTO" varchar(400) NULL,
  "ORIGEM_CANCELAMENTO" varchar(40) NULL,
  "GATEWAY_PROVIDER" varchar(40) NULL,
  "GATEWAY_CHARGE_ID" varchar(120) NULL,
  "PIX_TXID" varchar(120) NULL,
  "PIX_COPIA_COLA" text NULL,
  "PIX_QR_URL" text NULL,
  CONSTRAINT "CK_FIN_COB_MOD" CHECK ("MODALIDADE" IN ('CONEXAO', 'USO_PLATAFORMA')),
  CONSTRAINT "CK_FIN_COB_PAG" CHECK ("PAGADOR_TIPO" IN ('MOTORISTA', 'TENANT')),
  CONSTRAINT "CK_FIN_COB_STATUS" CHECK ("STATUS" IN ('ABERTA', 'PAGA', 'CANCELADA')),
  CONSTRAINT "CK_FIN_COB_MOEDA" CHECK ("MOEDA" = 'BRL'),
  CONSTRAINT "CK_FIN_COB_VALOR" CHECK ("VALOR_CENTAVOS" >= 0),
  CONSTRAINT "CK_FIN_COB_ORIGEM_CANC" CHECK (
    "ORIGEM_CANCELAMENTO" IS NULL
    OR "ORIGEM_CANCELAMENTO" IN ('TORRE', 'MOTORISTA', 'SISTEMA')
  )
);

-- Uma cobrança ABERTA de conexão por ciclo de confirmação.
CREATE UNIQUE INDEX IF NOT EXISTS "UK_FIN_COB_CICLO_ATIVA"
  ON "FIN_COBRANCA" ("IDCONVOCACAO", "ID_CICLO_CONFIRMACAO")
  WHERE "MODALIDADE" = 'CONEXAO' AND "STATUS" = 'ABERTA' AND "IDCONVOCACAO" IS NOT NULL;

-- No máximo uma cobrança ABERTA de conexão por convocação.
CREATE UNIQUE INDEX IF NOT EXISTS "UK_FIN_COB_CONV_ABERTA"
  ON "FIN_COBRANCA" ("IDCONVOCACAO")
  WHERE "MODALIDADE" = 'CONEXAO' AND "STATUS" = 'ABERTA' AND "IDCONVOCACAO" IS NOT NULL;

CREATE INDEX IF NOT EXISTS "IX_FIN_COB_TENANT_STATUS"
  ON "FIN_COBRANCA" ("TENANT_ID", "STATUS", "DH_CRIACAO" DESC);

CREATE INDEX IF NOT EXISTS "IX_FIN_COB_CONV"
  ON "FIN_COBRANCA" ("IDCONVOCACAO");

CREATE INDEX IF NOT EXISTS "IX_FIN_COB_PAGADOR_MOT"
  ON "FIN_COBRANCA" ("PAGADOR_CDCADASTRO")
  WHERE "PAGADOR_TIPO" = 'MOTORISTA';

CREATE INDEX IF NOT EXISTS "IX_FIN_COB_VIAGEM"
  ON "FIN_COBRANCA" ("TENANT_ID", "IDVIAGEM");

-- Eventos append-only.
CREATE TABLE IF NOT EXISTS "FIN_COBRANCA_EVENTO" (
  "ID" bigserial PRIMARY KEY,
  "ID_COBRANCA" bigint NOT NULL,
  "TIPO" varchar(40) NOT NULL,
  "STATUS_ANTERIOR" varchar(20) NULL,
  "STATUS_NOVO" varchar(20) NULL,
  "SGUSER" varchar(50) NULL,
  "DH_EVENTO" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "DETALHE" varchar(500) NULL,
  "IP" varchar(64) NULL,
  CONSTRAINT "FK_FIN_EVT_COB" FOREIGN KEY ("ID_COBRANCA")
    REFERENCES "FIN_COBRANCA" ("ID") ON DELETE RESTRICT,
  CONSTRAINT "CK_FIN_EVT_TIPO" CHECK ("TIPO" IN (
    'CRIADA', 'BAIXA_MANUAL', 'REVERSAO_BAIXA', 'CANCELADA'
  ))
);

CREATE INDEX IF NOT EXISTS "IX_FIN_EVT_COB"
  ON "FIN_COBRANCA_EVENTO" ("ID_COBRANCA", "DH_EVENTO");

-- Menu: Atlas Pay (módulo base / sistema).
INSERT INTO "TIPOATIVIDADE" ("CDTIPOATIVIDADE", "DSTIPOATIVIDADE", "DSPROGRAMA", "FGACTIVE", "FGGRUPO", "CD_MODULO_PRODUTO")
SELECT (SELECT COALESCE(MAX("CDTIPOATIVIDADE"), 0) + 1 FROM "TIPOATIVIDADE"),
  '9.7 Atlas Pay', 'atlas-pay', 'S', 'Sistema',
  (SELECT m."CD_MODULO" FROM "MODULO_PRODUTO" m WHERE m."CODIGO" = 'geral' LIMIT 1)
WHERE NOT EXISTS (
  SELECT 1 FROM "TIPOATIVIDADE" t WHERE TRIM(COALESCE(t."DSPROGRAMA", '')) = 'atlas-pay'
);

UPDATE "TIPOATIVIDADE" t
SET "DSTIPOATIVIDADE" = '9.7 Atlas Pay',
    "FGGRUPO" = COALESCE(NULLIF(TRIM(t."FGGRUPO"), ''), 'Sistema'),
    "FGACTIVE" = 'S'
WHERE TRIM(COALESCE(t."DSPROGRAMA", '')) = 'atlas-pay';

-- Libera o programa ao admin (e usuários que já têm Tenants SaaS), sem ativar regra financeira.
INSERT INTO "USUARIOATIVIDADE" ("SGUSUARIO", "CDTIPOATIVIDADE")
SELECT u."SGUSUARIO", t."CDTIPOATIVIDADE"
FROM "USUARIO" u
CROSS JOIN "TIPOATIVIDADE" t
WHERE TRIM(COALESCE(t."DSPROGRAMA", '')) = 'atlas-pay'
  AND u."FGACTIVE" IN ('S', 'A')
  AND (
    LOWER(TRIM(u."SGUSUARIO")) = 'admin'
    OR EXISTS (
      SELECT 1
      FROM "USUARIOATIVIDADE" ua2
      JOIN "TIPOATIVIDADE" t2 ON t2."CDTIPOATIVIDADE" = ua2."CDTIPOATIVIDADE"
      WHERE ua2."SGUSUARIO" = u."SGUSUARIO"
        AND TRIM(COALESCE(t2."DSPROGRAMA", '')) = 'gerenciar-tenants-saas'
    )
  )
  AND NOT EXISTS (
    SELECT 1 FROM "USUARIOATIVIDADE" x
    WHERE x."SGUSUARIO" = u."SGUSUARIO" AND x."CDTIPOATIVIDADE" = t."CDTIPOATIVIDADE"
  );
