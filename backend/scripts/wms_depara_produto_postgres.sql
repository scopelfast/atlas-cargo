-- WMS — De-para produto (código fornecedor/NF → código interno do dono + fator de conversão).
-- PostgreSQL, idempotente. Executar após wms_cadastros_mestre_postgres.sql (FK em "CD_DONO").

CREATE TABLE IF NOT EXISTS "WMS_DEPARA_PRODUTO" (
  "CD_DEPARA" SERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_DONO" INTEGER NOT NULL REFERENCES "WMS_DONO_ESTOQUE" ("CD_DONO") ON DELETE RESTRICT,
  "CODIGO_EXTERNO" VARCHAR(64) NOT NULL,
  "CODIGO_INTERNO" VARCHAR(128) NOT NULL,
  "FATOR_CONVERSAO" NUMERIC(18, 6) NOT NULL DEFAULT 1,
  "OBSERVACAO" VARCHAR(255),
  "FGACTIVE" CHAR(1) NOT NULL DEFAULT 'S',
  "DH_MAINTENANCE" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64),
  CONSTRAINT chk_wms_depara_fgactive CHECK ("FGACTIVE" IN ('S', 'N')),
  CONSTRAINT chk_wms_depara_fator_pos CHECK ("FATOR_CONVERSAO" > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_wms_depara_tenant_dono_codext
  ON "WMS_DEPARA_PRODUTO" ("TENANT_ID", "CD_DONO", LOWER(TRIM("CODIGO_EXTERNO")));

CREATE INDEX IF NOT EXISTS idx_wms_depara_tenant_dono ON "WMS_DEPARA_PRODUTO" ("TENANT_ID", "CD_DONO");
