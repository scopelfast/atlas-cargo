-- ============================================
-- Script para criar tabelas VIAGEMMOTORISTA e VIAGEMVEICULO
-- ============================================

USE [DIVULGACARGA_PRD];
GO

-- Tabela: VIAGEMMOTORISTA
IF NOT EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[VIAGEMMOTORISTA]') AND type in (N'U'))
BEGIN
    CREATE TABLE [dbo].[VIAGEMMOTORISTA] (
        [IDVIAGEM] DECIMAL(15, 0) NOT NULL,
        [CDMOTORISTA] DECIMAL(15, 0) NOT NULL,
        [DHMAINTENANCE] DATETIME NULL,
        [SGUSER] VARCHAR(50) NULL,
        [SERVERORIG] VARCHAR(50) NULL,
        CONSTRAINT [PK_VIAGEMMOTORISTA] PRIMARY KEY CLUSTERED ([IDVIAGEM] ASC, [CDMOTORISTA] ASC),
        CONSTRAINT [FK_VIAGEMMOTORISTA_VIAGEMMESTRE] FOREIGN KEY ([IDVIAGEM]) 
            REFERENCES [dbo].[VIAGEMMESTRE] ([IDVIAGEM]) ON DELETE CASCADE,
        CONSTRAINT [FK_VIAGEMMOTORISTA_CADASTROGERAL] FOREIGN KEY ([CDMOTORISTA]) 
            REFERENCES [dbo].[CADASTROGERAL] ([CDCADASTROGERAL]) ON DELETE CASCADE
    );
    
    PRINT '   ✓ Tabela VIAGEMMOTORISTA criada com sucesso.';
END
ELSE
BEGIN
    PRINT '   ⚠ Tabela VIAGEMMOTORISTA já existe.';
END
GO

-- Tabela: VIAGEMVEICULO
IF NOT EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[VIAGEMVEICULO]') AND type in (N'U'))
BEGIN
    CREATE TABLE [dbo].[VIAGEMVEICULO] (
        [IDVIAGEM] DECIMAL(15, 0) NOT NULL,
        [IDEQUIPAMENTO] DECIMAL(15, 0) NOT NULL,
        [REFEQUIPAMENTO] VARCHAR(20) NOT NULL,
        [TPEQUIPAMENTO] CHAR(2) NOT NULL,
        [DHMAINTENANCE] DATETIME NULL,
        [SGUSER] VARCHAR(50) NULL,
        [SERVERORIG] VARCHAR(50) NULL,
        CONSTRAINT [PK_VIAGEMVEICULO] PRIMARY KEY CLUSTERED ([IDVIAGEM] ASC, [IDEQUIPAMENTO] ASC),
        CONSTRAINT [FK_VIAGEMVEICULO_VIAGEMMESTRE] FOREIGN KEY ([IDVIAGEM]) 
            REFERENCES [dbo].[VIAGEMMESTRE] ([IDVIAGEM]) ON DELETE CASCADE,
        CONSTRAINT [FK_VIAGEMVEICULO_EQUIPAMENTO] FOREIGN KEY ([IDEQUIPAMENTO]) 
            REFERENCES [dbo].[EQUIPAMENTO] ([IDEQUIPAMENTO]) ON DELETE CASCADE
    );
    
    PRINT '   ✓ Tabela VIAGEMVEICULO criada com sucesso.';
END
ELSE
BEGIN
    PRINT '   ⚠ Tabela VIAGEMVEICULO já existe.';
END
GO

PRINT '';
PRINT '============================================';
PRINT 'Tabelas criadas com sucesso!';
PRINT '============================================';
GO

