  ON "WMS_NFE_SAIDA" ("TENANT_ID", "CD_DONO");

CREATE TABLE IF NOT EXISTS "WMS_CARGA_PROGRAMADA" (
  "CD_CARGA" SERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_DONO" INTEGER REFERENCES "WMS_DONO_ESTOQUE" ("CD_DONO") ON DELETE SET NULL,
  "CD_ROTA" INTEGER,
  "NM_ROTA" VARCHAR(120),
  "NM_DESCRICAO" VARCHAR(200),
  "TRANSPORTADORA_DOC" VARCHAR(20),
  "NM_MOTORISTA" VARCHAR(120),
  "PLACA" VARCHAR(10),
  "ST_CARGA" VARCHAR(20) NOT NULL DEFAULT 'RASCUNHO',
  "DH_CRIACAO" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64),
  "OBS" TEXT
