-- WMS — NF-e de saída (XML) + carga programada (agregação de notas).
-- PostgreSQL, idempotente. Executar após wms_cadastros_mestre_postgres.sql (FK CD_DONO).

CREATE TABLE IF NOT EXISTS "WMS_NFE_SAIDA" (
  "CD_NFE_SAIDA" SERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL DEFAULT 'default',
  "CD_DONO" INTEGER REFERENCES "WMS_DONO_ESTOQUE" ("CD_DONO") ON DELETE SET NULL,
  "CHAVE_NFE" CHAR(44) NOT NULL,
  "NUMERO_NF" VARCHAR(20),
  "SERIE" VARCHAR(15),
  "DH_EMISSAO" TIMESTAMPTZ,
  "CNPJ_EMITENTE" VARCHAR(14),
  "XNOME_EMIT" VARCHAR(255),
  "XMUN_EMIT" VARCHAR(120),
  "UF_EMIT" VARCHAR(2),
  "CNPJ_DEST" VARCHAR(14),
  "XNOME_DEST" VARCHAR(255),
  "CNPJ_ENTREGA" VARCHAR(14),
  "XNOME_ENTREGA" VARCHAR(255),
  "XLGR_DEST" VARCHAR(255),
  "NRO_DEST" VARCHAR(20),
  "XCPL_DEST" VARCHAR(120),
  "XBAIRRO_DEST" VARCHAR(120),
  "XMUN_DEST" VARCHAR(120),
  "UF_DEST" VARCHAR(2),
  "CEP_DEST" VARCHAR(8),
  "Q_ITENS" INTEGER NOT NULL DEFAULT 0,
  "LINHAS_JSON" JSONB,
  "DH_IMPORTACAO" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "SG_USER" VARCHAR(64)
);

