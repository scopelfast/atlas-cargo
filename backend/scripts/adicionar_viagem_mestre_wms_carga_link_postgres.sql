-- Vínculo WMS Carga programada / Rota operacional ↔ VIAGEMMESTRE (PostgreSQL)
-- Idempotente: ADD COLUMN IF NOT EXISTS + índices.
-- Execute após adicionar_wms_carga_rota_operacional_postgres.sql.

ALTER TABLE "VIAGEMMESTRE"
  ADD COLUMN IF NOT EXISTS "WMS_CD_CARGA" INTEGER NULL;

ALTER TABLE "VIAGEMMESTRE"
  ADD COLUMN IF NOT EXISTS "WMS_CD_ROTA_OPER" BIGINT NULL;

COMMENT ON COLUMN "VIAGEMMESTRE"."WMS_CD_CARGA" IS 'Carga programada WMS que originou a viagem (rascunho a partir da rota operacional).';
COMMENT ON COLUMN "VIAGEMMESTRE"."WMS_CD_ROTA_OPER" IS 'Versão da rota operacional WMS usada na geração (WMS_CARGA_ROTA_OPERACIONAL.CD_ROTA_OPER).';

CREATE INDEX IF NOT EXISTS "IX_VIAGEMMESTRE_WMS_CARGA"
  ON "VIAGEMMESTRE" ("TENANT_ID", "WMS_CD_CARGA")
  WHERE "WMS_CD_CARGA" IS NOT NULL;

ALTER TABLE "WMS_CARGA_ROTA_OPERACIONAL"
  ADD COLUMN IF NOT EXISTS "IDVIAGEM" BIGINT NULL;

COMMENT ON COLUMN "WMS_CARGA_ROTA_OPERACIONAL"."IDVIAGEM" IS 'Viagem gerada a partir desta versão da rota (Gerenciar Viagens).';

CREATE INDEX IF NOT EXISTS "IX_WMS_CARGA_ROTA_OP_VIAGEM"
  ON "WMS_CARGA_ROTA_OPERACIONAL" ("TENANT_ID", "IDVIAGEM")
  WHERE "IDVIAGEM" IS NOT NULL;
