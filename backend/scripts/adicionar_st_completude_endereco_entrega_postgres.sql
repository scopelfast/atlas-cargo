-- Status de completude do ponto de entrega (rascunho automático na importação NF-e).
-- PostgreSQL, idempotente.

ALTER TABLE "CADASTRO_ENDERECO_ENTREGA"
  ADD COLUMN IF NOT EXISTS "ST_COMPLETUDE" VARCHAR(16) NOT NULL DEFAULT 'COMPLETO';

COMMENT ON COLUMN "CADASTRO_ENDERECO_ENTREGA"."ST_COMPLETUDE" IS
  'COMPLETO = rota/coords ok; RASCUNHO = criado na importação NF-e, falta rota e/ou coordenadas.';

CREATE INDEX IF NOT EXISTS "IX_CAD_END_ENT_TENANT_ST_COMPLETUDE"
  ON "CADASTRO_ENDERECO_ENTREGA" ("TENANT_ID", "ST_COMPLETUDE")
  WHERE "FGACTIVE" = 'A';

ALTER TABLE "WMS_NFE_SAIDA"
  ADD COLUMN IF NOT EXISTS "CD_ENDERECO_ENTREGA" INTEGER;

COMMENT ON COLUMN "WMS_NFE_SAIDA"."CD_ENDERECO_ENTREGA" IS
  'Ponto de entrega vinculado (cadastro ou rascunho) após importação / provisionamento.';

CREATE INDEX IF NOT EXISTS "IX_WMS_NFE_SAIDA_ENDERECO_ENTREGA"
  ON "WMS_NFE_SAIDA" ("TENANT_ID", "CD_ENDERECO_ENTREGA")
  WHERE "CD_ENDERECO_ENTREGA" IS NOT NULL;
