-- WMS — Inventário (documento + linhas de contagem / snapshot).
-- PostgreSQL, idempotente. Executar no pgAdmin (ex.: atlas_cargo_prd) após backup.
-- Relacionado: docs/WMS_INVENTARIO_ORIENTACAO_PROCESSO.md, adicionar_wms_movimento_estoque_postgres.sql

CREATE TABLE IF NOT EXISTS "WMS_INVENTARIO" (
  "CD_INVENTARIO" SERIAL PRIMARY KEY,
  "TENANT_ID" VARCHAR(64) NOT NULL,
  "CD_DONO" INTEGER NOT NULL REFERENCES "WMS_DONO_ESTOQUE" ("CD_DONO") ON DELETE CASCADE,
  "TP_INVENTARIO" VARCHAR(16) NOT NULL DEFAULT 'GERAL',
  "ST_INVENTARIO" VARCHAR(20) NOT NULL DEFAULT 'EM_CONTAGEM',
  "DH_CORTE" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "DH_ABERTURA" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "DH_ENCERRAMENTO" TIMESTAMPTZ,
  "POLITICA_NAO_CONTADO" VARCHAR(16) NOT NULL DEFAULT 'MANTER',
  "OBSERVACAO" VARCHAR(500),
  "SG_USER" VARCHAR(64),
  CONSTRAINT ck_wms_inv_tp CHECK ("TP_INVENTARIO" IN ('INICIAL', 'GERAL')),
  CONSTRAINT ck_wms_inv_st CHECK (
    "ST_INVENTARIO" IN ('RASCUNHO', 'EM_CONTAGEM', 'CONFERIDO', 'ENCERRADO', 'CANCELADO')
  ),
  CONSTRAINT ck_wms_inv_pol_nao_contado CHECK ("POLITICA_NAO_CONTADO" IN ('MANTER', 'ZERAR'))
);

COMMENT ON TABLE "WMS_INVENTARIO" IS 'Inventário WMS por dono do estoque; encerramento gera WMS_MOVIMENTO_ESTOQUE (INVENTARIO_AJUSTE) por SKU.';
COMMENT ON COLUMN "WMS_INVENTARIO"."POLITICA_NAO_CONTADO" IS 'MANTER: itens só no snapshot não são zerados; ZERAR: tratados como contagem zero no encerramento.';

CREATE INDEX IF NOT EXISTS idx_wms_inv_tenant_dono
  ON "WMS_INVENTARIO" ("TENANT_ID", "CD_DONO", "DH_ABERTURA" DESC);

CREATE TABLE IF NOT EXISTS "WMS_INVENTARIO_LINHA" (
  "CD_LINHA" SERIAL PRIMARY KEY,
  "CD_INVENTARIO" INTEGER NOT NULL REFERENCES "WMS_INVENTARIO" ("CD_INVENTARIO") ON DELETE CASCADE,
  "CD_PRODUTO" INTEGER,
  "CODIGO_PRODUTO" VARCHAR(128) NOT NULL,
  "LOTE" VARCHAR(60),
  "VALIDADE" VARCHAR(10),
  "QTD_SISTEMA_SNAPSHOT" NUMERIC(18, 6) NOT NULL DEFAULT 0,
  "QTD_CONTADA" NUMERIC(18, 6),
  "FATOR_CONVERSAO" NUMERIC(18, 6) NOT NULL DEFAULT 1,
  "QTD_AJUSTE_SKU" NUMERIC(18, 6),
  "ORIGEM" VARCHAR(24) NOT NULL DEFAULT 'IMPORT',
  "ENDERECO" VARCHAR(120),
  "OBSERVACAO" VARCHAR(255),
  CONSTRAINT ck_wms_inv_lin_origem CHECK (
    "ORIGEM" IN ('SNAPSHOT', 'IMPORT', 'NAO_CONTADO_ZERAR', 'MANUAL')
  )
);

COMMENT ON TABLE "WMS_INVENTARIO_LINHA" IS 'Linhas de contagem; ajuste efetivo no encerramento é agregado por CD_PRODUTO (MVP Fase 1).';

CREATE INDEX IF NOT EXISTS idx_wms_inv_lin_inv
  ON "WMS_INVENTARIO_LINHA" ("CD_INVENTARIO");

CREATE INDEX IF NOT EXISTS idx_wms_inv_lin_prod
  ON "WMS_INVENTARIO_LINHA" ("CD_INVENTARIO", "CD_PRODUTO");

CREATE UNIQUE INDEX IF NOT EXISTS uq_wms_inv_lin_chave
  ON "WMS_INVENTARIO_LINHA" (
    "CD_INVENTARIO",
    LOWER(TRIM("CODIGO_PRODUTO")),
    COALESCE(LOWER(TRIM("LOTE")), ''),
    COALESCE(TRIM("VALIDADE"), '')
  );
