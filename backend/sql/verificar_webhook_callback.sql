-- Script para verificar retornos do webhook Meta
-- Use este script para verificar se os dados foram gravados corretamente

-- 1. Verificar uma convocação específica
SELECT 
    IDCONVOCACAO,
    IDVIAGEM,
    STATUS,
    DHRESPOSTA,
    LATITUDE,
    LONGITUDE,
    CDMOTIVORECUSA,
    DHMAINTENANCE,
    SGUSER,
    DHCONVOCACAO
FROM [dbo].[CONVOCACAO]
WHERE IDCONVOCACAO = 181  -- Altere para o ID que você quer verificar
ORDER BY DHMAINTENANCE DESC;

-- 2. Ver todas as convocações atualizadas pelo webhook (SGUSER = 'DESKRIO')
SELECT 
    IDCONVOCACAO,
    IDVIAGEM,
    STATUS,
    DHRESPOSTA,
    LATITUDE,
    LONGITUDE,
    CDMOTIVORECUSA,
    DHMAINTENANCE,
    SGUSER
FROM [dbo].[CONVOCACAO]
WHERE SGUSER = 'DESKRIO'
ORDER BY DHMAINTENANCE DESC;

-- 3. Ver convocações com resposta recente (últimas 24 horas)
SELECT 
    IDCONVOCACAO,
    IDVIAGEM,
    STATUS,
    DHRESPOSTA,
    LATITUDE,
    LONGITUDE,
    CDMOTIVORECUSA,
    DHMAINTENANCE,
    SGUSER,
    DATEDIFF(HOUR, DHRESPOSTA, GETDATE()) AS HORAS_ATRAS
FROM [dbo].[CONVOCACAO]
WHERE DHRESPOSTA IS NOT NULL
  AND SGUSER = 'DESKRIO'
  AND DHRESPOSTA >= DATEADD(HOUR, -24, GETDATE())
ORDER BY DHRESPOSTA DESC;

-- 4. Resumo: Quantas convocações foram atualizadas pelo webhook
SELECT 
    COUNT(*) AS TOTAL_ATUALIZADAS,
    SUM(CASE WHEN STATUS = 'ACEITA' THEN 1 ELSE 0 END) AS ACEITAS,
    SUM(CASE WHEN STATUS = 'RECUSADA' THEN 1 ELSE 0 END) AS RECUSADAS,
    SUM(CASE WHEN STATUS = 'PENDENTE' THEN 1 ELSE 0 END) AS PENDENTES,
    SUM(CASE WHEN LATITUDE IS NOT NULL AND LONGITUDE IS NOT NULL THEN 1 ELSE 0 END) AS COM_LOCALIZACAO
FROM [dbo].[CONVOCACAO]
WHERE SGUSER = 'DESKRIO';

