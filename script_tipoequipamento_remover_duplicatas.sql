-- =============================================================================
-- Remover duplicatas em TIPOEQUIPAMENTO (manter o registro de menor código)
-- e adicionar UNIQUE na descrição para evitar novas duplicatas.
-- =============================================================================
-- Execute este script UMA VEZ no PostgreSQL (pgAdmin ou psql) se já existirem
-- registros duplicados em DSTIPOEQUIPAMENTO.
-- =============================================================================

-- 1) Atualizar MODELOEQUIPAMENTO: apontar CDTIPOEQUIPAMENTO para o código que será mantido
UPDATE "MODELOEQUIPAMENTO" m
SET "CDTIPOEQUIPAMENTO" = sub."CD_MIN"
FROM (
  SELECT t."CDTIPOEQUIPAMENTO" AS CD_DUPLICADO,
         (SELECT MIN(t2."CDTIPOEQUIPAMENTO") FROM "TIPOEQUIPAMENTO" t2
          WHERE UPPER(TRIM(t2."DSTIPOEQUIPAMENTO")) = UPPER(TRIM(t."DSTIPOEQUIPAMENTO"))) AS CD_MIN
  FROM "TIPOEQUIPAMENTO" t
  WHERE t."CDTIPOEQUIPAMENTO" <> (
    SELECT MIN(t2."CDTIPOEQUIPAMENTO") FROM "TIPOEQUIPAMENTO" t2
    WHERE UPPER(TRIM(t2."DSTIPOEQUIPAMENTO")) = UPPER(TRIM(t."DSTIPOEQUIPAMENTO"))
  )
) sub
WHERE m."CDTIPOEQUIPAMENTO" = sub.CD_DUPLICADO;

-- 2) Atualizar EQUIPAMENTO (se existir referência a tipo)
UPDATE "EQUIPAMENTO" e
SET "CDTIPOEQUIPAMENTO" = sub."CD_MIN"
FROM (
  SELECT t."CDTIPOEQUIPAMENTO" AS CD_DUPLICADO,
         (SELECT MIN(t2."CDTIPOEQUIPAMENTO") FROM "TIPOEQUIPAMENTO" t2
          WHERE UPPER(TRIM(t2."DSTIPOEQUIPAMENTO")) = UPPER(TRIM(t."DSTIPOEQUIPAMENTO"))) AS CD_MIN
  FROM "TIPOEQUIPAMENTO" t
  WHERE t."CDTIPOEQUIPAMENTO" <> (
    SELECT MIN(t2."CDTIPOEQUIPAMENTO") FROM "TIPOEQUIPAMENTO" t2
    WHERE UPPER(TRIM(t2."DSTIPOEQUIPAMENTO")) = UPPER(TRIM(t."DSTIPOEQUIPAMENTO"))
  )
) sub
WHERE e."CDTIPOEQUIPAMENTO" = sub.CD_DUPLICADO;

-- 3) Atualizar MOTORISTA_VEICULO (se existir)
UPDATE "MOTORISTA_VEICULO" mv
SET "CDTIPOEQUIPAMENTO" = sub."CD_MIN"
FROM (
  SELECT t."CDTIPOEQUIPAMENTO" AS CD_DUPLICADO,
         (SELECT MIN(t2."CDTIPOEQUIPAMENTO") FROM "TIPOEQUIPAMENTO" t2
          WHERE UPPER(TRIM(t2."DSTIPOEQUIPAMENTO")) = UPPER(TRIM(t."DSTIPOEQUIPAMENTO"))) AS CD_MIN
  FROM "TIPOEQUIPAMENTO" t
  WHERE t."CDTIPOEQUIPAMENTO" <> (
    SELECT MIN(t2."CDTIPOEQUIPAMENTO") FROM "TIPOEQUIPAMENTO" t2
    WHERE UPPER(TRIM(t2."DSTIPOEQUIPAMENTO")) = UPPER(TRIM(t."DSTIPOEQUIPAMENTO"))
  )
) sub
WHERE mv."CDTIPOEQUIPAMENTO" = sub.CD_DUPLICADO;

-- 4) Excluir tipos duplicados (mantém o de menor código)
DELETE FROM "TIPOEQUIPAMENTO" a
WHERE EXISTS (
  SELECT 1 FROM "TIPOEQUIPAMENTO" b
  WHERE UPPER(TRIM(b."DSTIPOEQUIPAMENTO")) = UPPER(TRIM(a."DSTIPOEQUIPAMENTO"))
    AND b."CDTIPOEQUIPAMENTO" < a."CDTIPOEQUIPAMENTO"
);

-- 5) Adicionar constraint UNIQUE na descrição (evita novas duplicatas)
ALTER TABLE "TIPOEQUIPAMENTO"
  DROP CONSTRAINT IF EXISTS "uk_tipoequipamento_ds";
ALTER TABLE "TIPOEQUIPAMENTO"
  ADD CONSTRAINT "uk_tipoequipamento_ds" UNIQUE ("DSTIPOEQUIPAMENTO");
