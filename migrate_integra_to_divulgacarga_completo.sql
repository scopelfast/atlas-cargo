        ISNULL(VM.DHMAINTENANCE, GETDATE()) AS DHMAINTENANCE,
        UPPER(ISNULL(VM.SGUSER, 'SYSTEM')) AS SGUSER,
        ISNULL(VM.SERVERORIG, 'AppDVcargas') AS SERVERORIG
    FROM [INTEGRA_PRD].[dbo].[VIAGEMMESTRE] VM
    -- Subquery para detalhes do frete (concatenar parcelas)
    OUTER APPLY (
        SELECT 
            STUFF((
                SELECT CHAR(13) + CHAR(10) + 
                       TIPOPARCELA.DSTIPOPARCELA + ' - R$ ' + 
                       CONVERT(VARCHAR(20), CAST(VC.VLNEGOCIADO AS DECIMAL(15, 2)), 2)
                FROM [INTEGRA_PRD].[dbo].[VIAGEMCONTRATO] VC
                INNER JOIN [INTEGRA_PRD].[dbo].[TIPOPARCELA] TIPOPARCELA 
                    ON VC.SGTIPOPARCELA = TIPOPARCELA.SGTIPOPARCELA
                WHERE VC.IDVIAGEM = VM.IDVIAGEM
                  AND TIPOPARCELA.FGTIPOPARCELA IN ('F', 'O', 'A')
                ORDER BY VC.IDVIAGEM
                FOR XML PATH(''), TYPE
            ).value('.', 'NVARCHAR(MAX)'), 1, 2, '') AS DETALHES
    ) DETALHES_FRETE
    -- Subquery para valor total do frete
    OUTER APPLY (
        SELECT 
            CAST(SUM(VC.VLNEGOCIADO) AS DECIMAL(15, 4)) AS VLFRETE
        FROM [INTEGRA_PRD].[dbo].[VIAGEMCONTRATO] VC
        INNER JOIN [INTEGRA_PRD].[dbo].[TIPOPARCELA] TIPOPARCELA 
            ON VC.SGTIPOPARCELA = TIPOPARCELA.SGTIPOPARCELA
        WHERE VC.IDVIAGEM = VM.IDVIAGEM
          AND TIPOPARCELA.FGTIPOPARCELA IN ('F', 'O', 'A')
    ) VL_FRETE
    -- Subquery para calcular PESO e CUBAGEM
    OUTER APPLY (
        SELECT 
            SUM(COALESCE(SS.PESOPRODUTO, 0) + COALESCE(DFM.PESOBRUTO, 0)) AS PESO,
            SUM(COALESCE(SS.CUBAGEM, 0) + COALESCE(DFM.CUBAGEM, 0)) AS CUBAGEM
        FROM [INTEGRA_PRD].[dbo].[VIAGEMDOCUMENTO] VD
        LEFT JOIN [INTEGRA_PRD].[dbo].[SOLICITACAOSERVICO] SS 
            ON VD.SIGLADOC = 'SSV' AND VD.IDDOCUMENTO = SS.IDSOLICITACAOSERVICO
        LEFT JOIN [INTEGRA_PRD].[dbo].[DOCFISCALREF] DFR 
            ON VD.SIGLADOC <> 'SSV' AND VD.IDDOCUMENTO = DFR.IDDOCFISCAL
        LEFT JOIN [INTEGRA_PRD].[dbo].[DOCFISCALMESTRE] DFM 
            ON DFR.IDDOCREFERENCIA = DFM.IDDOCFISCAL
        WHERE VD.IDVIAGEM = VM.IDVIAGEM
    ) PESO_CUBAGEM
    WHERE VM.CDSITUACAOVIAGEM IN (1)
      AND VM.DHINCLUSAO > DATEADD(DAY, -30, GETDATE())
      AND VM.IDVIAGEM IS NOT NULL
) AS SOURCE
ON TARGET.IDVIAGEM = SOURCE.IDVIAGEM
WHEN NOT MATCHED BY TARGET THEN
    INSERT (
